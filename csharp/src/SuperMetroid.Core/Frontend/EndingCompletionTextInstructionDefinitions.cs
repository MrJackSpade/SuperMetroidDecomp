namespace SuperMetroid.Core.Frontend;

/// <summary>
/// Fixed bank-$8B typewriter programs for the ending's completion message and
/// clear time. The bank-$8C spritemap pointers identify the presented glyph
/// compositions; they do not define the text pacing or callback sequence.
/// </summary>
internal static class EndingCompletionTextInstructionDefinitions
{
    /// <summary>$8B:EB91, first word of THE OPERATION WAS.</summary>
    internal const ushort Start = 0xeb91;
    /// <summary>$8B:ECD9, exclusive end after the clear-time colon.</summary>
    internal const ushort End = 0xecd9;

    private static ReadOnlySpan<ushort> Program =>
    [
        // $EB91: THE OPERATION WAS, then its held final line.
        0x0008, 0xa69d, 0x0008, 0xa6a9, 0x000f, 0xa6bf, 0x0008, 0xa6df,
        0x0008, 0xa709, 0x0008, 0xa73d, 0x0008, 0xa77b, 0x0008, 0xa7c3,
        0x0008, 0xa815, 0x0008, 0xa871, 0x0008, 0xa8d7, 0x000f, 0xa947,
        0x0008, 0xa9c1, 0x0008, 0xaa45, 0x000f, 0xaad3, 0xf3b0, 0x000f,
        0xaad3, 0x94bc, 0xebcf,
        // $EBD7: COMPLETED SUCCESSFULLY, then its held final line.
        0x0008, 0xab6b, 0x0008, 0xab77, 0x0008, 0xab8d, 0x0008, 0xabad,
        0x0008, 0xabd7, 0x0008, 0xac0b, 0x0008, 0xac49, 0x0008, 0xac91,
        0x000f, 0xace3, 0x0008, 0xad3f, 0x0008, 0xada5, 0x0008, 0xae15,
        0x0008, 0xae8f, 0x0008, 0xaf13, 0x0008, 0xafa1, 0x0008, 0xb039,
        0x0008, 0xb0db, 0x0008, 0xb187, 0x0008, 0xb23d, 0x0008, 0xb2fd,
        0x000f, 0xb3c7, 0xf3ce, 0x0008, 0xb3c7, 0x94bc, 0xec2d,
        // $EC35: CLEAR TIME, four digit callbacks, colon, credits handoff.
        0x0008, 0xb49b, 0x0008, 0xb4a7, 0x0008, 0xb4bd, 0x0008, 0xb4dd,
        0x000f, 0xb507, 0x0008, 0xb53b, 0x0008, 0xb579, 0x0008, 0xb5c1,
        0x000f, 0xb613, 0xf41b, 0x0008, 0xb613, 0xf424, 0x0008, 0xb613,
        0xf42d, 0x0008, 0xb613, 0xf436, 0x0008, 0xb613, 0xf43f, 0x0080,
        0xb613, 0xf448, 0x000f, 0xb613, 0x94bc, 0xec79,
        // $EC81: ten digit loops followed by the colon loop at $ECD1.
        0x0008, 0xb67b, 0x94bc, 0xec81, 0x0008, 0xb687, 0x94bc, 0xec89,
        0x0008, 0xb693, 0x94bc, 0xec91, 0x0008, 0xb69f, 0x94bc, 0xec99,
        0x0008, 0xb6ab, 0x94bc, 0xeca1, 0x0008, 0xb6b7, 0x94bc, 0xeca9,
        0x0008, 0xb6c3, 0x94bc, 0xecb1, 0x0008, 0xb6cf, 0x94bc, 0xecb9,
        0x0008, 0xb6db, 0x94bc, 0xecc1, 0x0008, 0xb6e7, 0x94bc, 0xecc9,
        0x0008, 0xb66f, 0x94bc, 0xecd1,
    ];

    internal static ushort ReadWord(ushort pointer)
    {
        int offset = pointer - Start;
        if ((uint)offset >= End - Start || (offset & 1) != 0)
            throw new InvalidDataException(
                $"Ending completion instruction $8B:{pointer:X4} leaves its compiled lists.");
        return Program[offset / sizeof(ushort)];
    }
}
