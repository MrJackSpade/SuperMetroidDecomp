using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using SuperMetroid.EnsureAnalyzer.SourceLayout;

namespace SuperMetroid.EnsureAnalyzer.Generators;

/// <summary>
/// #2602: the verification registry, written at compile time so the verifier reaches its commands and named verifiers by
/// the code that names them instead of by scanning its assembly. For a compilation that declares
/// <c>SuperMetroid.Verification.Harness.VerificationCommandAttribute</c> it emits
/// <c>SuperMetroid.Verification.Harness.GeneratedVerificationRegistry</c>: each method carrying the attribute, with its
/// argument shape and a delegate that calls it; and each internal static method returning nothing or an exit code, which
/// <c>--suite</c> selects by name, with the one input it needs and a delegate that calls it.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class VerificationRegistryGenerator : IIncrementalGenerator
{
    private const string AttributeName = "SuperMetroid.Verification.Harness.VerificationCommandAttribute";
    private const string InstalledFixturesName = "SuperMetroid.TestSupport.RepositoryInstallation.Verification.InstalledFixtures";
    private const string InstallationName = "SuperMetroid.AssetExtraction.Installation.GameInstallation";

    private static readonly SymbolDisplayFormat Qualified = SymbolDisplayFormat.FullyQualifiedFormat;

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterSourceOutput(context.CompilationProvider, static (output, compilation) =>
        {
            if (compilation.GetTypeByMetadataName(AttributeName) is not { } attribute)
                return;
            output.AddSource("GeneratedVerificationRegistry.g.cs", Emit(compilation, attribute, output.CancellationToken));
        });

    private static string Emit(Compilation compilation, INamedTypeSymbol attribute, CancellationToken cancellation)
    {
        INamedTypeSymbol? fixtures = compilation.GetTypeByMetadataName(InstalledFixturesName);
        INamedTypeSymbol? installation = compilation.GetTypeByMetadataName(InstallationName);
        var fixtureProperties = fixtures is null
            ? ImmutableArray<IPropertySymbol>.Empty
            : [.. fixtures.GetMembers().OfType<IPropertySymbol>().Where(property => property.IsStatic && !property.IsIndexer &&
                property.DeclaredAccessibility is Accessibility.Internal or Accessibility.Private or Accessibility.ProtectedAndInternal &&
                property.GetMethod is not null)];
        var commands = new StringBuilder();
        var verifiers = new StringBuilder();
        foreach (IMethodSymbol method in Methods(compilation.Assembly.GlobalNamespace, cancellation))
        {
            if (!IsAuthored(method, cancellation) || !IsReachable(method.ContainingType))
                continue;
            foreach (AttributeData data in method.GetAttributes())
            {
                if (SymbolEqualityComparer.Default.Equals(data.AttributeClass, attribute))
                    commands.Append(Command(method, data));
            }
            if (method.DeclaredAccessibility == Accessibility.Internal && !method.IsGenericMethod &&
                (method.ReturnsVoid || method.ReturnType.SpecialType == SpecialType.System_Int32) &&
                !method.IsAbstract && !method.IsVirtual &&
                method.Parameters.All(parameter => parameter.RefKind == RefKind.None && !parameter.Type.IsRefLikeType && IsReachableType(parameter.Type)))
                verifiers.Append(Verifier(method, fixtureProperties, installation));
        }

        return $$"""
            // <auto-generated/>
            #nullable enable
            namespace SuperMetroid.Verification.Harness;

            /// <summary>The verifier's commands and named verifiers, written by the compiler from the code that declares them (#2602).</summary>
            internal static class GeneratedVerificationRegistry
            {
                /// <summary>Every method carrying a verification command attribute, once per attribute.</summary>
                internal static global::SuperMetroid.Verification.Harness.VerificationCommands.Command[] Commands() =>
                [
            {{commands}}    ];

                /// <summary>Every internal static method returning nothing or an exit code, which --suite selects by its name.</summary>
                internal static global::SuperMetroid.Verification.Harness.NamedVerifier[] Verifiers() =>
                [
            {{verifiers}}    ];
            }

            """;
    }

    private static string Command(IMethodSymbol method, AttributeData data)
    {
        string name = data.ConstructorArguments.Length > 0 ? data.ConstructorArguments[0].Value as string ?? "" : "";
        IEnumerable<string> arguments = data.ConstructorArguments.Length > 1 && data.ConstructorArguments[1].Kind == TypedConstantKind.Array
            ? data.ConstructorArguments[1].Values.Select(value => value.Value as string ?? "")
            : [];
        string description = data.NamedArguments.FirstOrDefault(pair => pair.Key == "Description").Value.Value as string ?? "";
        bool returnsInt = method.ReturnType.SpecialType == SpecialType.System_Int32;
        string[] parameterTypes = [.. method.Parameters.Select(parameter => parameter.Type.ToDisplayString())];
        bool takesArray = parameterTypes is ["string[]"];
        bool positional = parameterTypes.All(type => type == "string");
        string call = Call(method);
        string invoke = !returnsInt ? "null"
            : takesArray ? $"static values => {call}(values)"
            : positional ? $"static values => {call}({string.Join(", ", method.Parameters.Select((_, index) => $"values[{index}]"))})"
            : "null";
        return $"        new({Literal(name)}, [{string.Join(", ", arguments.Select(Literal))}], {Literal(description)}, {Literal(method.ContainingType.Name)}, " +
            $"{Literal(method.Name)}, {(returnsInt ? "true" : "false")}, [{string.Join(", ", parameterTypes.Select(Literal))}], {invoke}),\n";
    }

    private static string Verifier(IMethodSymbol method, ImmutableArray<IPropertySymbol> fixtures, INamedTypeSymbol? installation)
    {
        IParameterSymbol[] required = [.. method.Parameters.Where(parameter => !parameter.IsOptional)];
        string call = Call(method);
        string owner = Literal(method.ContainingType.Name);
        string name = Literal(method.Name);
        string result = method.ReturnsVoid ? "; return 0; }" : "; }";
        string open = method.ReturnsVoid ? "{ " : "{ return ";
        switch (required.Length)
        {
            case 0:
                return $"        new({name}, {owner}, global::SuperMetroid.Verification.Harness.NamedVerifierInput.None, static _ => {open}{call}(){result}),\n";
            case 1:
                // C# places required parameters before optional ones, so the one required input is the first argument and
                // the optional ones after it keep their defaults.
                ITypeSymbol type = required[0].Type;
                string invoke = $"static input => {open}{call}(({type.ToDisplayString(Qualified)})input!){result}";
                if (installation is not null && SymbolEqualityComparer.Default.Equals(type, installation))
                    return $"        new({name}, {owner}, global::SuperMetroid.Verification.Harness.NamedVerifierInput.Installation, {invoke}),\n";
                if (fixtures.FirstOrDefault(property => SymbolEqualityComparer.Default.Equals(property.Type, type)) is { } fixture &&
                    fixture.DeclaredAccessibility != Accessibility.Private)
                {
                    return $"        new({name}, {owner}, global::SuperMetroid.Verification.Harness.NamedVerifierInput.InstalledFixture, {invoke}, " +
                        $"Fixture: static () => {fixture.ContainingType.ToDisplayString(Qualified)}.{fixture.Name}),\n";
                }
                return $"        new({name}, {owner}, global::SuperMetroid.Verification.Harness.NamedVerifierInput.Cartridge, {invoke}, " +
                    $"Accepts: static value => value is {type.ToDisplayString(Qualified)}, InputName: {Literal(type.Name)}),\n";
            default:
                return $"        new({name}, {owner}, global::SuperMetroid.Verification.Harness.NamedVerifierInput.Prepared, static _ => 0, RequiredInputs: {required.Length}),\n";
        }
    }

    private static string Call(IMethodSymbol method) =>
        $"{method.ContainingType.ToDisplayString(Qualified)}.{(SyntaxFacts.GetKeywordKind(method.Name) == SyntaxKind.None ? "" : "@")}{method.Name}";

    private static IEnumerable<IMethodSymbol> Methods(INamespaceSymbol space, CancellationToken cancellation)
    {
        foreach (INamespaceOrTypeSymbol member in space.GetMembers())
        {
            cancellation.ThrowIfCancellationRequested();
            IEnumerable<IMethodSymbol> methods = member switch
            {
                INamespaceSymbol inner => Methods(inner, cancellation),
                INamedTypeSymbol type => TypeMethods(type),
                _ => [],
            };
            foreach (IMethodSymbol method in methods)
                yield return method;
        }
    }

    private static IEnumerable<IMethodSymbol> TypeMethods(INamedTypeSymbol type)
    {
        if (type.TypeKind.ToString() == "Extension" || type.IsGenericType)
            yield break;
        foreach (ISymbol member in type.GetMembers())
        {
            if (member is IMethodSymbol { IsStatic: true, MethodKind: MethodKind.Ordinary } method)
                yield return method;
            else if (member is INamedTypeSymbol nested)
                foreach (IMethodSymbol inner in TypeMethods(nested))
                    yield return inner;
        }
    }

    /// <summary>Whether generated code at namespace level can name the type and every type containing it.</summary>
    private static bool IsReachable(INamedTypeSymbol? type)
    {
        for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
        {
            if (current.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal) ||
                current.IsFileLocal || current.TypeKind.ToString() == "Extension" || current.IsGenericType)
                return false;
        }
        return true;
    }

    private static bool IsReachableType(ITypeSymbol type) => type switch
    {
        IArrayTypeSymbol array => IsReachableType(array.ElementType),
        INamedTypeSymbol named => IsReachable(named.OriginalDefinition.ContainingType) &&
            named.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal &&
            named.TypeArguments.All(IsReachableType),
        ITypeParameterSymbol => false,
        _ => type.TypeKind != TypeKind.Pointer && type.TypeKind != TypeKind.FunctionPointer,
    };

    private static bool IsAuthored(IMethodSymbol method, CancellationToken cancellation) =>
        method.DeclaringSyntaxReferences.Length > 0 &&
        method.DeclaringSyntaxReferences.All(reference => !GeneratedSource.IsSourceGeneratorOutput(reference.SyntaxTree, cancellation));

    private static string Literal(string value)
    {
        var sb = new StringBuilder("\"");
        foreach (char c in value)
        {
            sb.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                _ => c.ToString(),
            });
        }
        return sb.Append('"').ToString();
    }
}
