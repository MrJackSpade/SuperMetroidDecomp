    /// <summary>Number of non-debug room headers in the pinned retail revision.</summary>
    public const int RetailRoomCount = 262;

    static RoomHeaderDefinitions()
    {
        if (definitions.Length != RetailRoomCount)
        {
            throw new InvalidOperationException(
                $"Compiled room-header catalog contains {definitions.Length} records, not {RetailRoomCount}.");
        }

        for (int index = 1; index < definitions.Length; index++)
        {
            if (definitions[index - 1].Pointer >= definitions[index].Pointer)
            {
                throw new InvalidOperationException(
                    "Compiled room-header catalog pointers must be unique and sorted.");
            }
        }
    }

    /// <summary>Returns whether the pointer identifies one of the 262 retail room headers.</summary>
    public static bool Contains(ushort roomPointer) => FindIndex(roomPointer) >= 0;

    /// <summary>Returns the compiled fixed-header metadata for a retail room.</summary>
    public static RoomHeaderDefinition Get(ushort roomPointer)
    {
        int index = FindIndex(roomPointer);
        if (index < 0)
        {
            throw new ArgumentOutOfRangeException(nameof(roomPointer), roomPointer,
                "Pointer is not one of the 262 retail room headers.");
        }

        return definitions[index];
    }

    private static int FindIndex(ushort roomPointer)
    {
        int low = 0;
        int high = definitions.Length - 1;
        while (low <= high)
        {
            int middle = low + ((high - low) >> 1);
            int comparison = definitions[middle].Pointer.CompareTo(roomPointer);
            if (comparison == 0)
                return middle;
            if (comparison < 0)
                low = middle + 1;
            else
                high = middle - 1;
        }

        return -1;
    }
