    /// <summary>Adds the registrations of the collections, arrays, enums and generic game types a declared type names.</summary>
    internal void Codecs(ITypeSymbol type, HashSet<ITypeSymbol> seen, List<string> lines)
    {
        if (!seen.Add(type))
            return;
        switch (type)
        {
            case IArrayTypeSymbol array:
                Codecs(array.ElementType, seen, lines);
                if (array.Rank == 1)
                    lines.Add($"__registry.Array<{Code(array.ElementType)}>();");
                else if (array.Rank == 2)
                    lines.Add($"__registry.Grid<{Code(array.ElementType)}>();");
                return;
            case INamedTypeSymbol named:
                if (named.TypeKind == TypeKind.Enum)
                {
                    lines.Add(EnumRegistration(named));
                    return;
                }
                for (INamedTypeSymbol? container = named; container is not null; container = container.ContainingType)
                    foreach (ITypeSymbol argument in container.TypeArguments)
                        Codecs(argument, seen, lines);
                if (!named.IsGenericType || named.IsUnboundGenericType)
                {
                    Unheld(named, lines);
                    return;
                }
                string arguments = string.Join(", ", named.TypeArguments.Select(Code));
                string? kind = named.OriginalDefinition.ToDisplayString() switch
                {
                    "System.Collections.Generic.List<T>" => "List",
                    "System.Collections.Generic.Queue<T>" => "Queue",
                    "System.Collections.Generic.Stack<T>" => "Stack",
                    "System.Collections.Generic.HashSet<T>" => "HashSet",
                    "System.Collections.Generic.Dictionary<TKey, TValue>" => "Dictionary",
                    "System.Collections.Concurrent.ConcurrentDictionary<TKey, TValue>" => "ConcurrentDictionary",
                    "System.Collections.Immutable.ImmutableArray<T>" => "ImmutableArray",
                    "System.Collections.Immutable.ImmutableDictionary<TKey, TValue>" => "ImmutableDictionary",
                    "System.Collections.Immutable.ImmutableHashSet<T>" => "ImmutableHashSet",
                    "System.Collections.Frozen.FrozenDictionary<TKey, TValue>" => "FrozenDictionary",
                    "System.Collections.Frozen.FrozenSet<T>" => "FrozenSet",
                    "System.Collections.ObjectModel.ReadOnlyCollection<T>" => "ReadOnlyCollection",
                    "System.Lazy<T>" => "Lazy",
                    "System.Runtime.CompilerServices.ConditionalWeakTable<TKey, TValue>" => "Unheld",
                    "System.ReadOnlyMemory<T>" => "ReadOnlyMemory",
                    "System.Collections.Generic.IComparer<T>" or "System.Collections.Generic.IEqualityComparer<T>" => "Comparer",
                    "System.Collections.Generic.KeyValuePair<TKey, TValue>" => "KeyValuePair",
                    "System.Collections.Generic.IReadOnlyList<T>" or "System.Collections.Generic.IList<T>" or
                        "System.Collections.Generic.ICollection<T>" or "System.Collections.Generic.IReadOnlyCollection<T>" or
                        "System.Collections.Generic.IEnumerable<T>" => "Sequence",
                    "System.Collections.Generic.IReadOnlyDictionary<TKey, TValue>" or "System.Collections.Generic.IDictionary<TKey, TValue>" => "Map",
                    "System.Collections.Generic.IReadOnlySet<T>" or "System.Collections.Generic.ISet<T>" => "Set",
                    _ => null,
                };
                if (kind == "Unheld")
                {
                    lines.Add($"__registry.Unheld<{Code(named)}>();");
                    return;
                }
                if (kind == "ReadOnlyMemory")
                    lines.Add($"__registry.Array<{arguments}>();");
                if (kind is not null)
                {
                    lines.Add($"__registry.{kind}<{arguments}>();");
                    return;
                }
                if (named.OriginalDefinition.SpecialType != SpecialType.System_Nullable_T && named.TypeKind is TypeKind.Class or TypeKind.Struct && HasMembers(named))
                    lines.Add($"{Code(named)}.__StateRegister(__registry);");
                else
                    Unheld(named, lines);
                return;
            default:
                return;
        }
    }

    /// <summary>The element type of an inline array level, which every level with an inline length has.</summary>
    private static ITypeSymbol InlineElementOf(Level level) =>
        level.InlineElement ?? throw new InvalidOperationException($"{level.Declared} has an inline length but no element type.");

    /// <summary>The registration of an enum: its name, and whether its members compose as flags.</summary>
    private string EnumRegistration(INamedTypeSymbol named)
    {
        bool flags = named.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == "System.FlagsAttribute");
        return $"__registry.Enum<{Code(named)}>({NameExpression(named)}, {(flags ? "true" : "false")});";
    }

    /// <summary>
    /// Registers every enum the compilation declares. A generic type of the game holds a value of its type parameter, and
    /// code made generic constructs it with an enum no declaration names (<c>SequenceStep.Of&lt;TitleStep&gt;</c>, built by
    /// a step method its sequence calls with the step inferred), so an enum is registered whether or not a field names it.
    /// An enum code outside its containers cannot name is registered by its container, which a state registers in turn;
    /// one inside a generic type, which only a construction of the type can name, is registered by that construction's fields.
    /// </summary>
    private void RegisterEnums(INamespaceOrTypeSymbol container)
    {
        foreach (INamespaceOrTypeSymbol member in container.GetMembers().OfType<INamespaceOrTypeSymbol>())
        {
            if (member is INamedTypeSymbol { TypeKind: TypeKind.Enum } named)
            {
                // A file's own enum is held by no covered type: only code in its file can name it.
                if (named.IsImplicitlyDeclared || named.IsFileLocal || IsGenericContext(named))
                    continue;
                if (named.ContainingType is not { } owner || Accessible(named))
                    assemblyRegistrations.Add(EnumRegistration(named));
                else if (covered.Contains(owner))
                    AddRegistration(owner, EnumRegistration(named));
                continue;
            }
            RegisterEnums(member);
        }
    }

    /// <summary>Whether code outside the type's containers can name it: neither it nor a container is private or protected.</summary>
    private static bool Accessible(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
            if (current.IsFileLocal || current.DeclaredAccessibility is Accessibility.Private or Accessibility.Protected or Accessibility.ProtectedAndInternal)
                return false;
        return true;
    }

    /// <summary>
    /// Registers another assembly's class no registration names, such as a serializer's options a definition keeps: a
    /// state reaches nothing through it and refuses to hold it.
    /// </summary>
    private void Unheld(INamedTypeSymbol named, List<string> lines)
    {
        if (named.TypeKind == TypeKind.Class && !named.IsStatic && !IsGenericContext(named) &&
            named.SpecialType is SpecialType.None && named.ToDisplayString() is not ("System.Type" or "System.Exception") &&
            !named.IsUnboundGenericType && !HasMembers(named) &&
            !SymbolEqualityComparer.Default.Equals(named.ContainingAssembly, compilation.Assembly))
            lines.Add($"__registry.Unheld<{Code(named)}>();");
    }

    // ---------------------------------------------------------------- delegates

    /// <summary>
    /// Registers every method of a covered non-generic type that the compilation turns into a delegate, under the type
    /// that declares it, so a state names the method a delegate calls and remakes the delegate when restoring it.
    /// </summary>
    private void CollectDelegateMethods()
    {
        var names = new HashSet<string>(StringComparer.Ordinal);
        foreach (INamedTypeSymbol type in covered)
            foreach (IMethodSymbol method in type.GetMembers().OfType<IMethodSymbol>())
                if (method.MethodKind == MethodKind.Ordinary)
                    names.Add(method.Name);
        var registered = new HashSet<string>(StringComparer.Ordinal);
        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            SemanticModel? model = null;
            foreach (SyntaxNode node in tree.GetRoot(output.CancellationToken).DescendantNodes())
            {
                if (node is not ExpressionSyntax expression || !IsMethodGroupCandidate(expression, names))
                    continue;
                model ??= compilation.GetSemanticModel(tree);
                if (model.GetTypeInfo(expression, output.CancellationToken).ConvertedType is not INamedTypeSymbol { TypeKind: TypeKind.Delegate } delegateType ||
                    model.GetSymbolInfo(expression, output.CancellationToken).Symbol is not IMethodSymbol { MethodKind: MethodKind.Ordinary } method ||
                    !model.GetConversion(expression, output.CancellationToken).IsMethodGroup)
                    continue;
                INamedTypeSymbol declaring = method.ContainingType;
                if (!covered.Contains(declaring) || declaring.IsGenericType || IsGenericContext(delegateType) || method.TypeArguments.Any(IsGenericContext) ||
                    method.IsExtensionMethod)
                    continue;
                string name = $"{Declared(declaring)}::{method.Name}" +
                    (method.TypeArguments.Length > 0 ? "<" + string.Join(",", method.TypeArguments.Select(argument => argument.ToDisplayString())) + ">" : "") +
                    "(" + string.Join(",", method.Parameters.Select(parameter => parameter.Type.ToDisplayString())) + ")";
                if (!registered.Add(Code(delegateType) + "|" + name))
                    continue;
                string group = (method.IsStatic ? Code(declaring) : "__instance") + ".@" + method.Name +
                    (method.TypeArguments.Length > 0 ? "<" + string.Join(", ", method.TypeArguments.Select(Code)) + ">" : "");
                string create = method.IsStatic
                    ? $"static __target => __target is null ? new {Code(delegateType)}({group}) : null"
                    : $"static __target => __target is {Code(declaring)} __instance ? new {Code(delegateType)}({group}) : null";
                AddRegistration(declaring, $"__registry.Method<{Code(delegateType)}>({Literal(name)}, {create});");
            }
        }
    }

    private static bool IsMethodGroupCandidate(ExpressionSyntax expression, HashSet<string> names)
    {
        string? name = expression switch
        {
            IdentifierNameSyntax identifier when identifier.Parent is not MemberAccessExpressionSyntax { Name: var member } || member != identifier => identifier.Identifier.ValueText,
            GenericNameSyntax generic when generic.Parent is not MemberAccessExpressionSyntax { Name: var member } || member != generic => generic.Identifier.ValueText,
            MemberAccessExpressionSyntax access => access.Name.Identifier.ValueText,
            _ => null,
        };
        if (name is null || !names.Contains(name))
            return false;
        SyntaxNode? parent = expression.Parent;
        if (parent is InvocationExpressionSyntax invocation && invocation.Expression == expression)
            return false;
        if (parent is MemberAccessExpressionSyntax outer && outer.Expression == expression)
            return false;
        return parent is ArgumentSyntax or EqualsValueClauseSyntax or AssignmentExpressionSyntax or ArrowExpressionClauseSyntax or
            ReturnStatementSyntax or ConditionalExpressionSyntax or ExpressionElementSyntax or BinaryExpressionSyntax or
            InitializerExpressionSyntax or CastExpressionSyntax or ParenthesizedExpressionSyntax or SwitchExpressionArmSyntax;
    }

    private static bool IsGenericContext(ITypeSymbol type) => type switch
    {
        ITypeParameterSymbol => true,
        IArrayTypeSymbol array => IsGenericContext(array.ElementType),
        INamedTypeSymbol named => named.TypeArguments.Any(IsGenericContext) || named.ContainingType is { } container && IsGenericContext(container),
        _ => false,
    };

    // ---------------------------------------------------------------- catalogs

    /// <summary>
    /// Registers each covered non-generic type's static read-only members holding an object other than a string as a
    /// definition catalog (#1623), under the type that declares them, in their names' ordinal order.
    /// </summary>
    private void CollectCatalogs()
    {
        foreach (INamedTypeSymbol type in covered)
        {
            if (IsGenericContext(type) || type.IsGenericType)
                continue;
            var members = new List<(string Name, ITypeSymbol Type)>();
            foreach (IFieldSymbol field in type.GetMembers().OfType<IFieldSymbol>())
            {
                if (!field.IsStatic || field.IsConst || !field.IsReadOnly || field.Type.IsValueType ||
                    field.Type.SpecialType == SpecialType.System_String || field.Type.TypeKind is TypeKind.Pointer or TypeKind.FunctionPointer)
                    continue;
                string? name = field.AssociatedSymbol switch
                {
                    IPropertySymbol property => property.Name,
                    null when !field.IsImplicitlyDeclared => field.Name,
                    _ => null,
                };
                if (name is not null)
                    members.Add((name, field.Type));
            }
            if (members.Count == 0)
                continue;
            members.Sort((left, right) => string.CompareOrdinal(left.Name, right.Name));
            var seen = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
            var lines = new List<string>();
            foreach ((string _, ITypeSymbol memberType) in members)
                Codecs(memberType, seen, lines);
            foreach (string line in lines)
                AddRegistration(type, line);
            AddRegistration(type, $"__registry.Catalog({NameExpression(type)}, new {Core}StateGraphCatalogMember[] {{ " +
                string.Join(", ", members.Select(member => $"new({Literal(member.Name)}, {Literal(StateGraphExposure.Key(member.Type))}, static () => {Code(type)}.@{member.Name})")) +
                " });");
            CatalogTypes.Add(type);
            foreach ((string _, ITypeSymbol memberType) in members)
                CatalogMemberTypes.Add(memberType);
        }
    }

    /// <summary>The types registered as catalogs.</summary>
    internal List<INamedTypeSymbol> CatalogTypes { get; } = [];

    /// <summary>The types the catalogs' members are declared with.</summary>
    internal List<ITypeSymbol> CatalogMemberTypes { get; } = [];

    /// <summary>The compilation.</summary>
    internal Compilation Compilation => compilation;

    /// <summary>Every source type, in declaration order.</summary>
    internal IReadOnlyList<INamedTypeSymbol> Types => types;

    /// <summary>Reports a diagnostic.</summary>
    internal void Report(Diagnostic diagnostic) => output.ReportDiagnostic(diagnostic);

    // ---------------------------------------------------------------- registrar

    private string EmitRegistrar()
    {
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>");
        code.AppendLine("#nullable disable");
        code.AppendLine("#pragma warning disable");
        code.Append("namespace ").Append(compilation.AssemblyName ?? "StateGraph").AppendLine(";");
        code.AppendLine("/// <summary>Registers how a debugger state holds each type of this assembly (#2602).</summary>");
        code.AppendLine("public static class GeneratedStateGraph");
        code.AppendLine("{");
        code.AppendLine($"    /// <summary>Registers every type of this assembly with <paramref name=\"registry\"/>.</summary>");
        code.AppendLine($"    public static void Register({Registry} registry)");
        code.AppendLine("    {");
        code.AppendLine("        Types(registry);");
        code.AppendLine("        Exposure(registry);");
        code.AppendLine("    }");
        EmitChunked(code, "Types", [.. types.Where(type => covered.Contains(type) && type.ContainingType is null && type.TypeParameters.Length == 0)
            .Select(type => $"{Code(type)}.__StateRegister(__registry);")]);
        EmitChunked(code, "Exposure", assemblyRegistrations);
        code.AppendLine("}");
        return code.ToString();
    }

    /// <summary>The lines of one registration, split into methods of a few hundred lines, which the runtime compiles quickly.</summary>
    private static void EmitChunked(StringBuilder code, string name, IReadOnlyList<string> lines)
    {
        const int ChunkLines = 200;
        int chunks = (lines.Count + ChunkLines - 1) / ChunkLines;
        code.AppendLine($"    private static void {name}({Registry} __registry)");
        code.AppendLine("    {");
        for (int chunk = 0; chunk < chunks; chunk++)
            code.AppendLine($"        {name}{chunk}(__registry);");
        code.AppendLine("    }");
        for (int chunk = 0; chunk < chunks; chunk++)
        {
            code.AppendLine($"    private static void {name}{chunk}({Registry} __registry)");
            code.AppendLine("    {");
            foreach (string line in lines.Skip(chunk * ChunkLines).Take(ChunkLines))
                code.Append("        ").AppendLine(line);
            code.AppendLine("    }");
        }
    }
