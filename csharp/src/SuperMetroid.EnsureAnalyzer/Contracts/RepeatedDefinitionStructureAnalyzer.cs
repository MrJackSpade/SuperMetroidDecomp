using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using SuperMetroid.EnsureAnalyzer.CartridgeEncoding;
using SuperMetroid.EnsureAnalyzer.Modules;

namespace SuperMetroid.EnsureAnalyzer.Contracts;

/// <summary>
/// Repeated literal structure is stated once as data (SME6483, #2557): in a hand-written catalog file of
/// <c>SuperMetroid.Core</c> or <c>SuperMetroid.AssetExtraction</c> (<see cref="CartridgeEncodingScanner.IsCatalogFile"/>),
/// a list of two or more entries is not written out again entry for entry in another list of the same file, and a list
/// does not write one entry out three or more times in a row. The shared list is named once and referenced, and a run of
/// one entry is a count or a builder of it. Entries compare by their text with its spacing removed; generated catalogs
/// (<c>&lt;auto-generated/&gt;</c>) are their generators' to state once, and build output is skipped.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class RepeatedDefinitionStructureAnalyzer : DiagnosticAnalyzer
{
    /// <summary>A hand-written catalog repeats a list or an entry.</summary>
    public const string RepeatedDefinitionStructureId = "SME6483";

    /// <summary>The import pipeline's assembly, whose definition files hold data as Core's do.</summary>
    internal const string AssetExtractionAssembly = "SuperMetroid.AssetExtraction";

    /// <summary>How many times in a row one entry may be written before the run is a repeated structure.</summary>
    private const int RepeatedRun = 3;

    private static readonly DiagnosticDescriptor Rule = new(
        RepeatedDefinitionStructureId,
        "Catalog repeats a list or an entry",
        "The catalog '{0}' {1}; state the shared structure once: name the list and reference it, or build the run from its one entry and its count",
        "Design",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        description: "Definition data states a value, beat, arm or block shared by many entries once and references it by " +
            "name (#2557). A catalog that writes a list out again, entry for entry, or writes one entry out again and again " +
            "in a row lets the copies drift apart and hides what the entries share. The shared list becomes one named " +
            "definition, a mirrored or repeated run is derived from the one it repeats, and a run of one entry is built " +
            "from the entry and its count.");

    /// <inheritdoc/>
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => [Rule];

    /// <inheritdoc/>
    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(start =>
        {
            if (start.Compilation.AssemblyName is not (CoreLayerAnalyzer.CoreAssembly or AssetExtractionAssembly))
                return;
            start.RegisterSyntaxTreeAction(Analyze);
        });
    }

    /// <summary>Reports each repeated list and each run of one entry in an authored catalog file.</summary>
    private static void Analyze(SyntaxTreeAnalysisContext context)
    {
        SyntaxTree tree = context.Tree;
        if (!CartridgeEncodingScanner.IsCatalogFile(tree.FilePath) || CartridgeEncodingScanner.IsBuildGenerated(tree.FilePath))
            return;
        SyntaxNode root = tree.GetRoot(context.CancellationToken);
        if (root.GetLeadingTrivia().ToFullString().Contains("<auto-generated"))
            return;
        var lists = new Dictionary<string, Location>(StringComparer.Ordinal);
        foreach (SyntaxNode node in root.DescendantNodes())
        {
            IReadOnlyList<SyntaxNode>? entries = Entries(node);
            if (entries is null || entries.Count == 0)
                continue;
            string[] texts = [.. entries.Select(Text)];
            ReportRuns(context, node, entries, texts);
            if (entries.Count < 2)
                continue;
            string key = string.Join("\u0001", texts);
            if (lists.TryGetValue(key, out Location? first))
            {
                int line = first.GetLineSpan().StartLinePosition.Line + 1;
                Report(context, node, node.GetLocation(), $"writes out again the list of {entries.Count} entries it wrote at line {line}");
            }
            else
            {
                lists.Add(key, node.GetLocation());
            }
        }
    }

    /// <summary>Reports each run of one entry written <see cref="RepeatedRun"/> or more times in a row.</summary>
    private static void ReportRuns(SyntaxTreeAnalysisContext context, SyntaxNode list, IReadOnlyList<SyntaxNode> entries, string[] texts)
    {
        for (int start = 0; start < texts.Length;)
        {
            int end = start + 1;
            while (end < texts.Length && texts[end] == texts[start])
                end++;
            if (end - start >= RepeatedRun)
                Report(context, list, entries[start].GetLocation(), $"writes the entry '{Shortened(texts[start])}' out {end - start} times in a row");
            start = end;
        }
    }

    /// <summary>The entries of a collection expression or of an array, collection or object initializer; none for other syntax.</summary>
    private static IReadOnlyList<SyntaxNode>? Entries(SyntaxNode node) => node switch
    {
        CollectionExpressionSyntax collection => collection.Elements,
        InitializerExpressionSyntax initializer when !initializer.IsKind(SyntaxKind.ComplexElementInitializerExpression) => initializer.Expressions,
        _ => null,
    };

    /// <summary>An entry's text with its spacing and comments removed.</summary>
    private static string Text(SyntaxNode entry) =>
        string.Concat(entry.DescendantTokens().Select(token => token.Text));

    /// <summary>An entry's text cut short for a message.</summary>
    private static string Shortened(string text) => text.Length <= 60 ? text : text.Substring(0, 57) + "...";

    /// <summary>Reports one finding against the type that declares it, or against the file outside any type.</summary>
    private static void Report(SyntaxTreeAnalysisContext context, SyntaxNode node, Location location, string what)
    {
        string owner = node.FirstAncestorOrSelf<BaseTypeDeclarationSyntax>()?.Identifier.Text ??
            Path.GetFileName(node.SyntaxTree.FilePath);
        context.ReportDiagnostic(Diagnostic.Create(Rule, location, owner, what));
    }
}
