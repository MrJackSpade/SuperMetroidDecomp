using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using SuperMetroid.EnsureAnalyzer.Contracts;
using SuperMetroid.EnsureAnalyzer.Modules;
using SuperMetroid.EnsureVerification.Harness;

namespace SuperMetroid.EnsureVerification.Contracts;

/// <summary>Checks the #2187 literal-zero identity rule, SME6458.</summary>
internal static class LiteralZeroEnumAnalyzerTests
{
    /// <summary>The enums the fixtures use.</summary>
    private const string Types = """
        enum Item { Beam, Missile }
        [System.Flags] enum Buttons { None = 0, Jump = 1, Shoot = 2 }

        """;

    /// <summary>The advice every SME6458 message ends with.</summary>
    private const string Advice = "; name the member it means";

    /// <summary>One positive per place a zero can stand for an identity, and the named uses the rule leaves alone.</summary>
    internal static void VerifyLiteralZeroEnumAnalyzer()
    {
        // An argument, named or positional.
        Expect(Types + "class Hud { void Select(Item item) { } void Run() => Select(item: 0); }",
            "'item: 0' converts the literal zero to 'Item'" + Advice);
        Expect(Types + "class Hud { void Select(Item item) { } void Run() => Select(0); }",
            "'0' converts the literal zero to 'Item'" + Advice);
        // An assignment, a local and a field initializer, a return and an expression body.
        Expect(Types + "class Hud { Buttons _held; void Run() => _held = 0; }",
            "'_held = 0' converts the literal zero to 'Buttons'" + Advice);
        Expect(Types + "class Hud { void Run() { Buttons held = 0; _ = held; } }", "converts the literal zero to 'Buttons'" + Advice);
        Expect(Types + "class Hud { Item _item = 0; Item Read() => _item; }", "converts the literal zero to 'Item'" + Advice);
        Expect(Types + "class Hud { Item Read() { return 0; } }", "converts the literal zero to 'Item'" + Advice);
        // A coalescing default, into a nullable and through one.
        Expect(Types + "class Hud { Buttons Read(Buttons? held) => held ?? 0; }",
            "'held ?? 0' converts the literal zero to 'Buttons'" + Advice);
        Expect(Types + "class Hud { Buttons? Read() => 0; }", "converts the literal zero to 'Buttons'" + Advice);
        // Any integral constant zero, not only the decimal literal.
        Expect(Types + "class Hud { Item Read() => 0x0; }", "converts the literal zero to 'Item'" + Advice);
        // A case label and a constant pattern.
        Expect(Types + "class Hud { int Read(Item item) { switch (item) { case 0: return 1; default: return 2; } } }",
            "converts the literal zero to 'Item'" + Advice);
        Expect(Types + "class Hud { bool Read(Item item) => item is 0; }", "converts the literal zero to 'Item'" + Advice);
        // A checked-in generator's output is Core source like any other.
        Expect("// <auto-generated/>\n" + Types + "class Hud { Item Read() => 0; }", "converts the literal zero to 'Item'" + Advice);

        // A parameter's default is read where it is declared, once, and not at the calls that leave it out.
        Expect(Types + "class Hud { void Select(Item item = 0) { } void Run() { Select(); Select(); } }",
            "converts the literal zero to 'Item'" + Advice);
        Expect(Types + "class Hud { void Select(Item item = Item.Missile) { } void Run() { Select(); } }", count: 0);
        // Named members, defaults and other numbers are not literal zeros.
        Expect(Types + "class Hud { void Select(Item item) { } void Run() { Select(Item.Beam); Buttons held = Buttons.None; _ = held; } }", count: 0);
        Expect(Types + "class Hud { Buttons Read(Buttons? held) => held ?? Buttons.None; Item Other() => default; }", count: 0);
        Expect(Types + "class Hud { int Count(int count = 0) => count; long Wide() => 0; }", count: 0);
        // A comparison or arithmetic with the literal is SME6450's read, not a second finding here.
        Expect(Types + "class Hud { bool Read(Buttons held) => (held & Buttons.Jump) != 0; }", count: 0);
        // Outside Core the rule does not apply.
        Expect(Types + "class Importer { Item Read() => 0; }", count: 0, assemblyName: "SuperMetroid.AssetExtraction");
    }

    /// <summary>Compiles one source and compares the SME6458 count and an optional message fragment.</summary>
    private static void Expect(string source, string? message = null, int count = 1, string assemblyName = CoreLayerAnalyzer.CoreAssembly)
    {
        var tree = CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Preview),
            path: "C:/fixture-repo/csharp/src/SuperMetroid.Core/Frontend/Fixture.cs");
        var compilation = CSharpCompilation.Create(assemblyName, [tree], AnalyzerTests.References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException($"Invalid analyzer fixture: {string.Join("; ", errors.Select(e => e.ToString()))}");
        var diagnostics = compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new LiteralZeroEnumAnalyzer()))
            .GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();
        if (diagnostics.Length != count ||
            diagnostics.Any(d => d.Id != LiteralZeroEnumAnalyzer.LiteralZeroEnumId || d.Severity != DiagnosticSeverity.Error) ||
            (message is not null && !diagnostics.All(d => d.GetMessage().Contains(message, StringComparison.Ordinal))))
        {
            throw new InvalidOperationException(
                $"Expected {count} {LiteralZeroEnumAnalyzer.LiteralZeroEnumId} diagnostic(s) containing '{message}', " +
                $"got [{string.Join("; ", diagnostics.Select(d => d.ToString()))}] in: {source}");
        }
    }
}
