namespace SuperMetroid.AssetExtraction.Audio;

/// <summary>
/// Build-stage extractor for the game's exact SPC upload streams and their inspectable
/// derivatives. Lossless <c>.spcu</c> files retain native provenance while decoded music/SFX
/// programs and instrument records become editable definitions; a deduplicated stable-ID WAV
/// catalog supplies every runtime sample. This deliberately makes authored audio replacement
/// independent from the managed sequencer and mixer mechanics.
/// </summary>
public static class SpcAudioAssetExtractor
{

    /// <summary>Extracts runtime audio directly from a user's cartridge, without raw files or an upstream checkout.</summary>
    public static AudioAssetManifest Extract(CartridgeImportAddressSpace cartridge, string audioDirectory)
    {
        Ensure.NotNull(cartridge);
        return Extract(definition => SpcUploadStreamReader.Read(cartridge, definition.SnesAddress, includeExecutionAddress: true), audioDirectory);
    }

    /// <summary>Writes validated SPC streams, decoded programs, and deduplicated WAV samples from a supplied reader.</summary>
    internal static AudioAssetManifest Extract(Func<AudioUploadAssetDefinition, byte[]> readStream, string audioDirectory)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(audioDirectory);
        audioDirectory = Path.GetFullPath(audioDirectory);

        string streamsDirectory = Path.Combine(audioDirectory, "streams");
        string samplesDirectory = Path.Combine(audioDirectory, "samples");
        Directory.CreateDirectory(streamsDirectory);
        // This directory is wholly generated by this extractor. Rebuilding it atomically at
        // the directory level prevents obsolete per-bank WAVs from masquerading as live assets.
        if (Directory.Exists(samplesDirectory))
            Directory.Delete(samplesDirectory, recursive: true);
        Directory.CreateDirectory(samplesDirectory);

        List<AudioUploadManifestEntry> uploads = [];
        Dictionary<int, byte[]> sourceStreams = [];
        foreach (AudioUploadAssetDefinition definition in AudioAssetCatalogDefinitions.All)
        {
            byte[] stream = readStream(definition);
            ValidateUploadStream(stream, definition.Name);
            string relativePath = Path.Combine("streams", $"{definition.DataIndex:X2}-{definition.Name}.spcu");
            File.WriteAllBytes(Path.Combine(audioDirectory, relativePath), stream);
            sourceStreams.Add(definition.SnesAddress, stream);
            uploads.Add(new AudioUploadManifestEntry(
                definition.SnesAddress,
                relativePath.Replace('\\', '/'),
                Convert.ToHexString(SHA256.HashData(stream))));
        }

        byte[] commonRam = new byte[SpcDriverDefinitions.ApuRamSize];
        bool[] commonWritten = new bool[SpcDriverDefinitions.ApuRamSize];
        ApplyUpload(commonRam, commonWritten, sourceStreams[AudioAssetCatalogDefinitions.Common.SnesAddress]);

        var canonicalSamples = new CanonicalSampleBuilder(audioDirectory, samplesDirectory);
        List<AudioBankMetadata> banks =
        [
            ExtractBankMetadata(
                AudioAssetCatalogDefinitions.Common,
                commonRam,
                commonWritten,
                canonicalSamples,
                includeTrackPointers: false),
        ];
        foreach (AudioUploadAssetDefinition definition in AudioAssetCatalogDefinitions.Music)
        {
            byte[] ram = (byte[])commonRam.Clone();
            bool[] written = (bool[])commonWritten.Clone();
            ApplyUpload(ram, written, sourceStreams[definition.SnesAddress]);
            banks.Add(ExtractBankMetadata(
                definition,
                ram,
                written,
                canonicalSamples,
                includeTrackPointers: true));
        }

        IReadOnlyList<AudioSoundLibraryMetadata> soundLibraries = ExtractSoundLibraries(
            commonRam,
            commonWritten,
            out IReadOnlyList<AudioSoundProgramMetadata> soundPrograms);
        AudioAssetManifest manifest = new(
            AudioAssetManifest.CurrentFormatVersion,
            uploads,
            canonicalSamples.Metadata,
            banks,
            soundPrograms,
            soundLibraries);
        // Stream the UTF-8 JSON into the file; the manifest is large enough that one
        // intermediate string per install dominated extraction allocation.
        using (var output = File.Create(Path.Combine(audioDirectory, ExtractedAudioAssetCatalog.ManifestFileName)))
            JsonSerializer.Serialize(output, manifest, AudioAssetJson.Options);
        return manifest;
    }

    /// <summary>Decodes one uploaded bank's track pointers, instrument records, and BRR sample directory.</summary>
    private static AudioBankMetadata ExtractBankMetadata(
        AudioUploadAssetDefinition definition,
        byte[] ram,
        bool[] written,
        CanonicalSampleBuilder canonicalSamples,
        bool includeTrackPointers)
    {
        List<ushort> trackPointers = [];
        if (includeTrackPointers)
        {
            int tableAddress = SpcDriverDefinitions.Ram.DefaultMusicPointer;
            int firstFollowingContent = SpcDriverDefinitions.ApuRamSize;
            for (int track = 0; track < MaximumTrackPointerCount; track++)
            {
                int entryAddress = tableAddress + track * 2;
                if (entryAddress >= firstFollowingContent)
                    break;
                ushort pointer = ReadWord(ram, entryAddress);
                if (pointer != 0 && !written[pointer])
                    throw new InvalidDataException(
                        $"{definition.Name} track {track} points outside uploaded content at ${pointer:X4}.");
                trackPointers.Add(pointer);
                // Music data may precede the table, but the first pointer at or above the
                // table is the exact boundary immediately following its final entry. Stop
                // there instead of misreading that track's phrase-flow words as more tracks.
                if (pointer >= tableAddress && pointer < firstFollowingContent)
                    firstFollowingContent = pointer;
            }
            if (firstFollowingContent == SpcDriverDefinitions.ApuRamSize)
                throw new InvalidDataException($"{definition.Name} track table has no following-content boundary.");
        }
        SpcMusicDefinitionBundle music = includeTrackPointers
            ? SpcMusicDefinitionCodec.DecodeBank(
                definition.DataIndex,
                trackPointers,
                ram,
                written)
            : new([], [], []);

        List<AudioInstrumentMetadata> instruments = [];
        int instrumentCount = SpcDriverDefinitions.Ram.InstrumentCount;
        for (int instrument = 0; instrument < instrumentCount; instrument++)
        {
            int address = SpcDriverDefinitions.Ram.InstrumentTable +
                instrument * SpcDriverDefinitions.Ram.InstrumentRecordSize;
            byte source = ram[address];
            instruments.Add(new AudioInstrumentMetadata(
                instrument,
                (source & SpcDriverDefinitions.Instruments.NoiseMarker) != 0,
                source,
                ram[address + 1],
                ram[address + 2],
                ram[address + 3],
                unchecked(SnesLittleEndian.Word(ram[address + 5], ram[address + 4]))));
        }

        List<AudioSampleMetadata> samples = [];
        ushort firstSampleAddress = ReadWord(ram, BrrDirectoryAddress);
        int directoryBytes = firstSampleAddress - BrrDirectoryAddress;
        if (directoryBytes <= 0 || directoryBytes % BrrDirectoryEntrySize != 0 ||
            directoryBytes / BrrDirectoryEntrySize > byte.MaxValue + 1)
        {
            throw new InvalidDataException(
                $"{definition.Name} has invalid BRR directory boundary ${firstSampleAddress:X4}.");
        }
        int sourceCount = directoryBytes / BrrDirectoryEntrySize;
        for (int source = 0; source < sourceCount; source++)
        {
            int directory = BrrDirectoryAddress + source * BrrDirectoryEntrySize;
            ushort start = ReadWord(ram, directory);
            ushort loop = ReadWord(ram, directory + 2);
            if (start == 0 || !written[start])
                continue;
            if (!TryDecodeBrr(ram, written, start, loop, out short[] pcm, out _, out int? loopSample))
                continue;

            string sampleId = canonicalSamples.Add(
                definition.DataIndex,
                unchecked((byte)source),
                pcm,
                loopSample);
            samples.Add(new AudioSampleMetadata(
                unchecked((byte)source), start, loop, sampleId));
        }

        return new AudioBankMetadata(
            definition.Name,
            definition.DataIndex,
            definition.SnesAddress,
            trackPointers,
            music.Tracks,
            music.Phrases,
            music.Programs,
            instruments,
            samples);
    }

    /// <summary>Resolves common-RAM sound commands to reusable channel programs across three libraries.</summary>
    private static List<AudioSoundLibraryMetadata> ExtractSoundLibraries(
        byte[] commonRam,
        bool[] commonWritten,
        out IReadOnlyList<AudioSoundProgramMetadata> programs)
    {
        List<AudioSoundLibraryMetadata> libraries = [];
        Dictionary<ushort, AudioSoundProgramMetadata> programsByAddress = [];
        for (int library = 0; library < SpcDriverDefinitions.SoundEffects.LibraryCount; library++)
        {
            int commandCount = SpcSoundEffectTables.CommandCount(library);
            List<AudioSoundEffectMetadata> effects = [];
            for (int index = 0; index < commandCount; index++)
            {
                ushort streamPointer = SpcSoundEffectTables.StreamPointer(library, index + 1);
                byte configuration = SpcSoundEffectTables.Configuration(library, index + 1);
                int voiceCount = SpcSoundEffectTables.GetVoiceCount(library, configuration);
                var channelPrograms = new string[voiceCount];
                for (int channel = 0; channel < voiceCount; channel++)
                {
                    int pointerAddress = streamPointer + channel * 2;
                    if (pointerAddress > ushort.MaxValue - 1 ||
                        !commonWritten[pointerAddress] || !commonWritten[pointerAddress + 1])
                    {
                        throw new InvalidDataException(
                            $"SFX library {library + 1} command ${index + 1:X2} channel {channel} " +
                            $"pointer at ${pointerAddress:X4} is outside common uploaded content.");
                    }
                    ushort programAddress = ReadWord(commonRam, pointerAddress);
                    if (!programsByAddress.TryGetValue(programAddress, out AudioSoundProgramMetadata? program))
                    {
                        string id = $"sfx-program-{programAddress:x4}";
                        program = SpcSoundEffectProgramCodec.Decode(
                            id,
                            programAddress,
                            commonRam,
                            commonWritten);
                        programsByAddress.Add(programAddress, program);
                    }
                    channelPrograms[channel] = program.Id;
                }
                effects.Add(new AudioSoundEffectMetadata(
                    unchecked((byte)(index + 1)),
                    $"sfx-{library + 1}-{index + 1:x2}",
                    streamPointer,
                    configuration,
                    channelPrograms));
            }
            libraries.Add(new AudioSoundLibraryMetadata(library + 1, effects));
        }
        programs = programsByAddress.Values.OrderBy(program => program.Address).ToArray();
        return libraries;
    }

    /// <summary>Builds an exact finite PCM prefix and recurring loop from BRR predictor states.</summary>
    internal static bool TryDecodeBrr(
        byte[] ram,
        bool[] written,
        ushort start,
        ushort loop,
        out short[] pcm,
        out int blockCount,
        out int? loopSampleIndex)
    {
        List<short> samples = [];
        HashSet<ushort> blockAddresses = [];
        Dictionary<BrrHistory, int> loopHistories = [];
        int address = start;
        int old = 0;
        int older = 0;
        bool followingLoop = false;
        blockCount = 0;
        while (samples.Count < BrrExtractionLimits.MaximumDecodedLoopSamples)
        {
            if (!followingLoop && blockCount >= MaximumBrrBlocks)
                break;
            if (address > ushort.MaxValue - BrrBlockByteLength)
                break;
            for (int index = 0; index < BrrBlockByteLength; index++)
            {
                if (!written[address + index])
                    goto Invalid;
            }

            blockAddresses.Add(unchecked((ushort)address));
            byte header = ram[address];
            int shift = header >> 4;
            int filter = (header >> 2) & 3;
            if (address == loop)
            {
                // A loop is repeatable only when it returns to the same predictor
                // history, not merely the same BRR address. Filter zero discards both
                // history words, so its entry state can be normalized immediately.
                var history = filter == 0 ? new BrrHistory(0, 0) : new BrrHistory(old, older);
                if (followingLoop && loopHistories.TryGetValue(history, out int repeatAt))
                {
                    pcm = [.. samples];
                    loopSampleIndex = repeatAt;
                    return true;
                }
                loopHistories.TryAdd(history, samples.Count);
            }
            for (int sampleIndex = 0; sampleIndex < PcmSampleFormat.StreamingWindowSampleCount; sampleIndex++)
            {
                byte packed = ram[address + 1 + sampleIndex / 2];
                int sample = (sampleIndex & 1) == 0 ? packed >> 4 : packed & 0x0f; // cartridge-encoding: allow(Codec) - BRR low sample nibble
                if (sample > 7)
                    sample -= 16;
                sample = shift <= 12 ? (sample << shift) >> 1 : (sample >> 3) << 12;
                sample += filter switch
                {
                    0 => 0,
                    1 => old + (-old >> 4),
                    2 => 2 * old + ((3 * -old) >> 5) - older + (older >> 4),
                    3 => 2 * old + ((13 * -old) >> 6) - older + ((3 * older) >> 4),
                    _ => throw new InvalidDataException($"Impossible BRR filter {filter}."),
                };
                sample = Math.Clamp(sample, short.MinValue, short.MaxValue);
                sample = unchecked((short)((sample & 0x7fff) << 1)) >> 1; // cartridge-encoding: allow(Codec) - BRR fifteen-bit sample wrap
                older = old;
                old = sample;
                samples.Add(unchecked((short)sample));
            }
            address += BrrBlockByteLength;
            if (!followingLoop) blockCount++;
            if ((header & 1) != 0)
            {
                if ((header & 2) == 0)
                {
                    pcm = [.. samples];
                    loopSampleIndex = null;
                    return true;
                }
                if (!blockAddresses.Contains(loop)) goto Invalid;
                // Keep transient loop passes in the WAV prefix. Once the exact
                // history repeats, the remaining cycle is ordinary replaceable PCM;
                // the runtime needs neither a BRR decoder nor special loop effects.
                followingLoop = true;
                address = loop;
            }
        }

        if (followingLoop)
            throw new InvalidDataException(
                $"BRR sample ${start:X4} loop ${loop:X4} did not reach a repeated decoder state " +
                $"within {BrrExtractionLimits.MaximumDecodedLoopSamples} PCM frames.");

    Invalid:
        pcm = [];
        blockCount = 0;
        loopSampleIndex = null;
        return false;
    }

    /// <summary>Rejects malformed SPC upload records before publishing a raw stream asset.</summary>
    private static void ValidateUploadStream(ReadOnlySpan<byte> stream, string name)
    {
        byte[] scratch = new byte[SpcDriverDefinitions.ApuRamSize];
        bool[] written = new bool[SpcDriverDefinitions.ApuRamSize];
        try
        {
            ApplyUpload(scratch, written, stream);
        }
        catch (InvalidDataException exception)
        {
            throw new InvalidDataException($"Raw audio asset '{name}' is not a valid SPC upload stream.", exception);
        }
    }

    /// <summary>Copies upload records into APU RAM and marks each byte populated for later decoding.</summary>
    private static void ApplyUpload(byte[] ram, bool[] written, ReadOnlySpan<byte> stream)
    {
        int offset = 0;
        for (;;)
        {
            if (offset > stream.Length - 2)
                throw new InvalidDataException("SPC upload ended before its terminating length word.");
            ushort length = unchecked(SnesLittleEndian.Word(stream[offset], stream[offset + 1]));
            offset += 2;
            if (length == 0)
            {
                // Retail assets retain the two-byte SPC execution address consumed by the
                // upload handshake after its zero-length marker. The managed driver already
                // runs, so playback ignores it while extraction preserves it byte-for-byte.
                if (stream.Length - offset is not 0 and not 2)
                    throw new InvalidDataException($"SPC upload has {stream.Length - offset} unexpected bytes after its terminator.");
                return;
            }
            if (offset > stream.Length - 2)
                throw new InvalidDataException("SPC upload ended before a destination word.");
            ushort destination = unchecked(SnesLittleEndian.Word(stream[offset], stream[offset + 1]));
            offset += 2;
            if (length > stream.Length - offset)
                throw new InvalidDataException($"SPC upload record ${destination:X4} overruns its source stream.");
            if (destination + length > ram.Length)
                throw new InvalidDataException($"SPC upload record ${destination:X4}+${length:X4} overruns APU RAM.");
            stream.Slice(offset, length).CopyTo(ram.AsSpan(destination, length));
            Array.Fill(written, true, destination, length);
            offset += length;
        }
    }

    /// <summary>Reads an SPC pointer from two little-endian RAM bytes.</summary>
    private static ushort ReadWord(byte[] bytes, int address) =>
        unchecked(SnesLittleEndian.Word(bytes[address], bytes[address + 1]));

    /// <summary>
    /// Assigns the first cartridge occurrence of a unique waveform/loop pair a readable,
    /// durable identity. Content hashes are only deduplication and integrity mechanisms:
    /// replacing a WAV later does not force callers to rename its sample ID.
    /// </summary>
    private sealed class CanonicalSampleBuilder
    {
        /// <summary>Installation root used to publish stable relative WAV paths.</summary>
        private readonly string audioDirectory;
        /// <summary>Generated WAV directory rebuilt for the current extraction.</summary>
        private readonly string samplesDirectory;
        /// <summary>Deduplicates identical waveforms and loop positions across upload banks.</summary>
        private readonly Dictionary<string, string> idsByContent = new(StringComparer.Ordinal);
        /// <summary>Manifest records for each distinct published PCM sample.</summary>
        private readonly List<AudioCanonicalSampleMetadata> metadata = [];

        /// <summary>Prepares stable sample IDs relative to the installed audio root.</summary>
        internal CanonicalSampleBuilder(string audioDirectory, string samplesDirectory)
        {
            this.audioDirectory = audioDirectory;
            this.samplesDirectory = samplesDirectory;
        }

        /// <summary>Published sample metadata in first-cartridge-occurrence order.</summary>
        internal IReadOnlyList<AudioCanonicalSampleMetadata> Metadata => metadata;

        /// <summary>Reuses a matching waveform or writes a stable-ID WAV with its integrity hash.</summary>
        internal string Add(byte dataIndex, byte source, short[] pcm, int? loopSampleIndex)
        {
            byte[] pcmBytes = new byte[checked(pcm.Length * sizeof(short))];
            Buffer.BlockCopy(pcm, 0, pcmBytes, 0, pcmBytes.Length);
            string contentKey = $"{PcmSampleFormat.StockSampleRate}:{loopSampleIndex?.ToString() ?? "-"}:" +
                Convert.ToHexString(SHA256.HashData(pcmBytes));
            if (idsByContent.TryGetValue(contentKey, out string? existingId))
                return existingId;

            string id = $"sample-{dataIndex:X2}-{source:X2}".ToLowerInvariant();
            string absolutePath = Path.Combine(samplesDirectory, id + ".wav");
            PcmWaveFile.WriteMonoPcm16(absolutePath, PcmSampleFormat.StockSampleRate, pcm);
            byte[] waveBytes = File.ReadAllBytes(absolutePath);
            string relativePath = Path.GetRelativePath(audioDirectory, absolutePath).Replace('\\', '/');
            metadata.Add(new AudioCanonicalSampleMetadata(
                id,
                relativePath,
                PcmSampleFormat.StockSampleRate,
                pcm.Length,
                loopSampleIndex,
                Convert.ToHexString(SHA256.HashData(waveBytes))));
            idsByContent.Add(contentKey, id);
            return id;
        }
    }
}
