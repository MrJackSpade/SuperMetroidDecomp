    /// <summary>Resolves scroll words.</summary>
    extension(RoomScrollDefinitions)
    {
        /// <summary>The scroll definition a room state's <paramref name="word"/> selects.</summary>
        internal static RoomScrollDefinition Get(ushort word) => ByWord.TryGetValue(word, out RoomScrollDefinition? found)
            ? found
            : throw new ArgumentOutOfRangeException(nameof(word), word, "Word is not a retail room-state scroll selection.");

        /// <summary>The word room states store for <paramref name="scroll"/>.</summary>
        internal static ushort PointerOf(RoomScrollDefinition scroll) => ByWord.Single(pair => ReferenceEquals(pair.Value, scroll)).Key;
    }

    /// <summary>The scroll word of a room state.</summary>
    extension(RoomStateSettings self)
    {
        /// <summary>The word this state stores for its scroll data.</summary>
        internal ushort ScrollPointer => RoomScrollDefinitions.PointerOf(self.Scroll);
    }
