    /// <summary>Returns one of the six areas exported by the retail save routines.</summary>
    public static ExploredMapPackingDefinition Area(int area) => area switch
    {
        0 => new(0x0000, 0x8146, CrateriaIndexes),
        1 => new(0x004a, 0x8196, BrinstarIndexes),
        2 => new(0x0092, 0x81e6, NorfairIndexes),
        3 => new(0x00de, 0x8236, WreckedShipIndexes),
        4 => new(0x00f0, 0x8256, MaridiaIndexes),
        5 => new(0x0132, 0x82a6, TourianIndexes),
        _ => throw new ArgumentOutOfRangeException(nameof(area)),
    };
}

/// <summary>One area's packed-SRAM destination and ordered explored-map byte indexes.</summary>
internal readonly record struct ExploredMapPackingDefinition(
    ushort DestinationOffset,
    ushort NativeSourcePointer,
    ReadOnlyMemory<byte> AreaByteIndexes);
