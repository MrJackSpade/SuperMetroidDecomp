using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SuperMetroid.EnsureAnalyzer.Generators;

/// <summary>The code a state-graph run writes for each type and for the assembly (#2602).</summary>
internal sealed partial class StateGraphRun
{
    /// <summary>Adds a registration line to a type's own registration.</summary>
    internal void AddRegistration(INamedTypeSymbol type, string line)
    {
        type = type.OriginalDefinition;
        if (!extraRegistrations.TryGetValue(type, out List<string>? lines))
            extraRegistrations[type] = lines = [];
        lines.Add(line);
    }

    /// <summary>Adds a line to the assembly registrar.</summary>
    internal void AddAssemblyRegistration(string line) => assemblyRegistrations.Add(line);

    private string EmitType(INamedTypeSymbol type)
    {
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>");
        code.AppendLine("#nullable disable");
        code.AppendLine("#pragma warning disable");
        if (type.ContainingNamespace is { IsGlobalNamespace: false } space)
            code.Append("namespace ").Append(space.ToDisplayString()).AppendLine(";");
        var chain = new List<INamedTypeSymbol>();
        for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
            chain.Insert(0, current);
        foreach (INamedTypeSymbol level in chain)
        {
            code.Append(Declaration(level));
            // A generic type's constructions may be made where no declaration names them, so each object registers its own.
            if (SymbolEqualityComparer.Default.Equals(level, type) && LevelOf(type) is not null && IsGenericContext(type))
                code.Append($" : {Core}IStateGraphNode");
            code.AppendLine().AppendLine("{");
        }
        EmitMembers(type, code);
        foreach (INamedTypeSymbol _ in chain)
            code.AppendLine("}");
        return code.ToString();
    }

    /// <summary>The partial declaration line of a type.</summary>
    private static string Declaration(INamedTypeSymbol type)
    {
        var line = new StringBuilder();
        if (type.IsStatic)
            line.Append("static ");
        if (type.TypeKind == TypeKind.Struct && type.IsReadOnly)
            line.Append("readonly ");
        if (type.IsRefLikeType)
            line.Append("ref ");
        line.Append("partial ");
        line.Append(type.TypeKind == TypeKind.Struct ? type.IsRecord ? "record struct " : "struct " : type.IsRecord ? "record " : "class ");
        line.Append(SyntaxFacts.GetKeywordKind(type.Name) != SyntaxKind.None ? "@" + type.Name : type.Name);
        if (type.TypeParameters.Length > 0)
            line.Append('<').Append(string.Join(", ", type.TypeParameters.Select(parameter => parameter.Name))).Append('>');
        return line.ToString();
    }

    private void EmitMembers(INamedTypeSymbol type, StringBuilder code)
    {
        Level? level = LevelOf(type);
        var registration = new List<string>();
        string self = Code(type);
        if (level is not null)
        {
            EmitLevel(level, code);
            string? schema = level.IsStruct && !type.IsGenericType ? PackedSchema(level, []) : null;
            string create = type.IsAbstract ? "null" : $"static __reader => new {self}(__reader, default)";
            if (type.IsAbstract)
                registration.Add($"__registry.Name(typeof({self}), {NameExpression(type)});");
            else
                registration.Add($"__registry.Node<{self}>({NameExpression(type)}, static (__writer, __value) => __value.__StateWriteRestoreOrder_{level.Suffix}(__writer), {create}, static (__value, __visitor) => __value.__StateVisit_{level.Suffix}(__visitor), {(schema is null ? "null" : Literal(schema))});");
            var seen = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
            foreach (Member member in level.Own)
                Codecs(member.Type, seen, registration);
            if (level.InlineElement is not null)
                Codecs(level.InlineElement, seen, registration);
            if (level.Primary is not null)
                foreach (IParameterSymbol parameter in level.Primary.Parameters)
                    Codecs(parameter.Type, seen, registration);
            // A generic base's construction registers what its own fields are declared with in this construction.
            if (level.Base is not null)
                Codecs(level.Base, seen, registration);
        }
        else
        {
            registration.Add($"__registry.Name(typeof({self}), {NameExpression(type)});");
        }
        // What static fields hold is walked when a definition catalog or a bound fixture reaches it.
        var staticSeen = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
        foreach (IFieldSymbol field in type.GetMembers().OfType<IFieldSymbol>())
            if (field.IsStatic && !field.IsConst && field.Type.TypeKind is not (TypeKind.Pointer or TypeKind.FunctionPointer))
                Codecs(field.Type, staticSeen, registration);
        foreach (INamedTypeSymbol nested in type.GetTypeMembers())
        {
            if (covered.Contains(nested) && nested.TypeParameters.Length == 0)
                registration.Add($"{Code(nested)}.__StateRegister(__registry);");
        }
        if (extraRegistrations.TryGetValue(type, out List<string>? extra))
            registration.AddRange(extra);
        if (level is not null && IsGenericContext(type))
            code.AppendLine($"    void {Core}IStateGraphNode.Describe({Registry} __registry) => __StateRegister(__registry);");
        code.AppendLine($"    internal static void __StateRegister({Registry} __registry)");
        code.AppendLine("    {");
        code.AppendLine($"        if (!__registry.Begin(typeof({self}))) return;");
        foreach (string line in registration)
            code.Append("        ").AppendLine(line);
        code.AppendLine("    }");
    }

    private void EmitLevel(Level level, StringBuilder code)
    {
        string access = level.Access;
        string s = level.Suffix;
        // Field names, the way a state names each field.
        for (int index = 0; index < level.Own.Count; index++)
            code.AppendLine($"    private static readonly {FieldType} __StateField_{s}_{index} = new({Literal(level.Declared)}, {Literal(level.Own[index].Name)});");
        if (level.InlineLength > 0)
        {
            code.Append($"    private static readonly {FieldType}[] __StateElements_{s} = [");
            code.Append(string.Join(", ", Enumerable.Range(0, level.InlineLength).Select(index => $"new({Literal(level.Declared)}, \"#{index}\")")));
            code.AppendLine("];");
        }
        int mapped = level.Arguments.Count(argument => argument is not null);
        if (level.Primary is not null)
        {
            for (int index = 0; index < level.Primary.Parameters.Length; index++)
                code.AppendLine($"    private static readonly {FieldType} __StateArgumentField_{s}_{index} = new({Literal(level.Declared)}, {Literal("(" + level.Primary.Parameters[index].Name + ")")});");
            if (!level.IsSealed)
            {
                for (int index = 0; index < level.Primary.Parameters.Length; index++)
                {
                    IParameterSymbol parameter = level.Primary.Parameters[index];
                    string argumentAccess = IsPublicSignature(parameter.Type) || level.Type.DeclaredAccessibility != Accessibility.Public ? "protected" : "private protected";
                    code.AppendLine($"    {argumentAccess} {Code(parameter.Type)} __StateArgument_{s}_{index}() => {level.Arguments[index] ?? "default"};");
                }
            }
        }

        // The whole object in restore order.
        code.AppendLine($"    {access} void __StateWriteRestoreOrder_{s}({Writer} __writer)");
        code.AppendLine("    {");
        if (level.Primary is not null)
        {
            if (mapped > 0)
            {
                code.AppendLine($"        __writer.Fields({mapped});");
                for (int index = 0; index < level.Primary.Parameters.Length; index++)
                {
                    if (level.Arguments[index] is not { } argument)
                        continue;
                    code.AppendLine($"        __writer.Field(__StateArgumentField_{s}_{index});");
                    code.AppendLine("        " + WriteValue(level.Primary.Parameters[index].Type, argument));
                }
            }
            code.AppendLine($"        this.__StateWriteOwn_{s}(__writer);");
            foreach (Level inherited in Inherited(level))
                code.AppendLine($"        this.__StateWriteOwnAll_{inherited.Suffix}(__writer);");
        }
        else
        {
            if (level.Base is not null)
                code.AppendLine($"        this.__StateWriteRestoreOrder_{Suffix(level.Base.OriginalDefinition)}(__writer);");
            code.AppendLine($"        this.__StateWriteOwn_{s}(__writer);");
        }
        code.AppendLine("    }");

        // The level's own fields.
        code.AppendLine($"    {access} void __StateWriteOwn_{s}({Writer} __writer)");
        code.AppendLine("    {");
        if (level.InlineLength > 0)
        {
            code.AppendLine($"        __writer.Fields({level.InlineLength});");
            code.AppendLine($"        for (int __index = 0; __index < {level.InlineLength}; __index++)");
            code.AppendLine("        {");
            code.AppendLine($"            __writer.Field(__StateElements_{s}[__index]);");
            code.AppendLine("            " + WriteValue(InlineElementOf(level), "this[__index]"));
            code.AppendLine("        }");
        }
        else
        {
            WriteMembers(level, code, all: false);
        }
        code.AppendLine("    }");

        // Every one of the level's own fields, which a derived primary constructor's restore order writes.
        if (!level.IsSealed)
        {
            code.AppendLine($"    {access} void __StateWriteOwnAll_{s}({Writer} __writer)");
            code.AppendLine("    {");
            if (level.InlineLength > 0)
                code.AppendLine($"        this.__StateWriteOwn_{s}(__writer);");
            else
                WriteMembers(level, code, all: true);
            code.AppendLine("    }");
        }

        // The level's own fields that can reach another object.
        code.AppendLine($"    {access} void __StateVisitOwn_{s}({Visitor} __visitor)");
        code.AppendLine("    {");
        if (level.InlineLength > 0)
        {
            if (level.InlineElement is { } inlineElement && HoldsReferences(inlineElement, []))
                code.AppendLine($"        for (int __index = 0; __index < {level.InlineLength}; __index++) __visitor.Child(__StateElements_{s}[__index], this[__index]);");
        }
        else
        {
            for (int index = 0; index < level.Own.Count; index++)
            {
                if (HoldsReferences(level.Own[index].Type, []))
                    code.AppendLine($"        __visitor.Child(__StateField_{s}_{index}, {level.Own[index].Expression});");
            }
        }
        code.AppendLine("    }");
        code.AppendLine($"    {access} void __StateVisit_{s}({Visitor} __visitor)");
        code.AppendLine("    {");
        if (level.Base is not null)
            code.AppendLine($"        this.__StateVisit_{Suffix(level.Base.OriginalDefinition)}(__visitor);");
        code.AppendLine($"        this.__StateVisitOwn_{s}(__visitor);");
        code.AppendLine("    }");

        // Restores the level's own fields after a derived primary constructor built it.
        if (!level.IsSealed)
        {
            code.AppendLine($"    {access} void __StateRestoreOwn_{s}({Reader} __reader)");
            code.AppendLine("    {");
            code.AppendLine($"        __reader.Fields({level.Own.Count});");
            for (int index = 0; index < level.Own.Count; index++)
            {
                Member member = level.Own[index];
                code.AppendLine($"        __reader.Field(__StateField_{s}_{index});");
                string read = ReadValue(member.Type);
                code.AppendLine("        " + (member.Kind switch
                {
                    MemberKind.FixedProperty => $"__reader.Fixed({member.Expression});",
                    MemberKind.Field when member.Readonly => $"global::System.Runtime.CompilerServices.Unsafe.AsRef(in {member.Expression}) = {read};",
                    MemberKind.Field or MemberKind.SettableProperty or MemberKind.Captured => $"{member.Expression} = {read};",
                    _ => throw new InvalidOperationException($"No restore of a {member.Kind}."),
                }));
            }
            code.AppendLine("    }");
        }

        // A class that declares no constructor keeps the parameterless one the compiler gave it before the restore
        // constructor was added.
        if (!level.IsStruct && level.Primary is null && level.Type.InstanceConstructors.All(constructor => constructor.IsImplicitlyDeclared))
            code.AppendLine($"    {(level.Type.IsAbstract ? "protected" : "public")} {EscapedName(level.Type)}() {{ }}");

        // The restore constructor.
        code.AppendLine("    [global::System.Diagnostics.CodeAnalysis.SetsRequiredMembers]");
        code.Append($"    {(level.IsSealed ? "private" : "protected")} {EscapedName(level.Type)}({Reader} __reader, {Restore} __restore)");
        if (level.Primary is not null)
        {
            var arguments = new List<string>();
            int ordinal = 0;
            for (int index = 0; index < level.Primary.Parameters.Length; index++)
            {
                IParameterSymbol parameter = level.Primary.Parameters[index];
                arguments.Add(level.Arguments[index] is null
                    ? "default"
                    : $"__reader.Argument<{Code(parameter.Type)}>({ordinal++}, {mapped}, __StateArgumentField_{s}_{index}, out {Code(parameter.Type)} __argument{index})");
            }
            code.AppendLine($" : this({string.Join(", ", arguments)})");
        }
        else if (level.Base is not null)
        {
            code.AppendLine(" : base(__reader, __restore)");
        }
        else
        {
            code.AppendLine();
        }
        code.AppendLine("    {");
        if (!level.IsStruct)
            code.AppendLine("        __reader.Created(this);");
        if (level.InlineLength > 0)
        {
            code.AppendLine($"        __reader.Fields({level.InlineLength});");
            code.AppendLine($"        for (int __index = 0; __index < {level.InlineLength}; __index++)");
            code.AppendLine("        {");
            code.AppendLine($"            __reader.Field(__StateElements_{s}[__index]);");
            code.AppendLine($"            this[__index] = {ReadValue(InlineElementOf(level))};");
            code.AppendLine("        }");
        }
        else
        {
            code.AppendLine($"        __reader.Fields({level.Restored.Count});");
            for (int index = 0; index < level.Own.Count; index++)
            {
                Member member = level.Own[index];
                if (level.Exact.Contains(member.Name))
                    continue;
                code.AppendLine($"        __reader.Field(__StateField_{s}_{index});");
                // A captured parameter is set by the primary constructor's argument; its value is read past.
                code.AppendLine(member.Kind == MemberKind.Captured
                    ? $"        _ = {ReadValue(member.Type)};"
                    : $"        {member.Expression} = {ReadValue(member.Type)};");
            }
        }
        if (level.Primary is not null)
        {
            foreach (Level inherited in Inherited(level))
                code.AppendLine($"        this.__StateRestoreOwn_{inherited.Suffix}(__reader);");
        }
        code.AppendLine("    }");
    }

    /// <summary>Writes the level's own fields: all of them, or all but those its primary constructor sets exactly.</summary>
    private static void WriteMembers(Level level, StringBuilder code, bool all)
    {
        int count = all ? level.Own.Count : level.Restored.Count;
        code.AppendLine($"        __writer.Fields({count});");
        for (int index = 0; index < level.Own.Count; index++)
        {
            if (!all && level.Exact.Contains(level.Own[index].Name))
                continue;
            code.AppendLine($"        __writer.Field(__StateField_{level.Suffix}_{index});");
            code.AppendLine("        " + WriteValue(level.Own[index].Type, level.Own[index].Expression));
        }
    }

    private static string EscapedName(INamedTypeSymbol type) =>
        SyntaxFacts.GetKeywordKind(type.Name) != SyntaxKind.None ? "@" + type.Name : type.Name;

    private static bool IsPublicSignature(ITypeSymbol type) => type switch
    {
        IArrayTypeSymbol array => IsPublicSignature(array.ElementType),
        ITypeParameterSymbol => true,
        INamedTypeSymbol named => IsPublic(named) && named.TypeArguments.All(IsPublicSignature),
        _ => true,
    };

    private static bool IsPublic(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
            if (current.DeclaredAccessibility != Accessibility.Public)
                return false;
        return true;
    }

