using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using SuperMetroid.EnsureAnalyzer.Contracts;
using SuperMetroid.EnsureAnalyzer.Modules;
using SuperMetroid.EnsureVerification.Harness;

namespace SuperMetroid.EnsureVerification.Contracts;

/// <summary>Checks the #2557 repeated-structure rule, SME6483.</summary>
internal static class RepeatedDefinitionStructureAnalyzerTests
{
    /// <summary>A catalog file by the encoding scanner's suffix list.</summary>
    private const string Catalog = "C:/fixture-repo/csharp/src/SuperMetroid.Core/Rooms/DoorDefinitions.cs";

    /// <summary>A functional Core file.</summary>
    private const string Functional = "C:/fixture-repo/csharp/src/SuperMetroid.Core/Rooms/DoorScroll.cs";

    /// <summary>The advice every SME6483 message ends with.</summary>
    private const string Advice = "; state the shared structure once: name the list and reference it, or build the run from its one entry and its count";

    /// <summary>The domain types the fixtures construct.</summary>
    private const string Types = """
        enum Side { Left, Right }
        sealed record Door(Side Side, int Frames);

        """;

    /// <summary>The repeated list and the run of one entry, and the shapes the rule leaves alone.</summary>
    internal static void VerifyRepeatedDefinitionStructureAnalyzer()
    {
        // One list written out again, entry for entry, in another list of the file; the spacing does not tell them apart.
        Expect(Types + """
            static class DoorDefinitions
            {
                static readonly Door[] Left = [new(Side.Left, 4), new(Side.Right, 8)];
                static readonly Door[] Again = [new(Side.Left,4),
                    new(Side.Right, 8)];
            }
            """, "The catalog 'DoorDefinitions' writes out again the list of 2 entries it wrote at line 5" + Advice);
        // An initializer repeats a collection expression's list too.
        Expect(Types + """
            static class DoorDefinitions
            {
                static readonly int[] Frames = [4, 8];
                static readonly int[] Again = new[] { 4, 8 };
            }
            """, "writes out again the list of 2 entries");
        // One entry three times in a row.
        Expect(Types + "static class DoorDefinitions { static readonly int[] Frames = [4, 4, 4, 8]; }",
            "The catalog 'DoorDefinitions' writes the entry '4' out 3 times in a row" + Advice);

        // The shared list named once and referenced; a list differing in one entry; a run of two; a one-entry list repeated.
        Expect(Types + """
            static class DoorDefinitions
            {
                static readonly Door[] Shared = [new(Side.Left, 4), new(Side.Right, 8)];
                static readonly Door[][] Both = [Shared, Shared];
                static readonly Door[] Other = [new(Side.Left, 4), new(Side.Right, 16)];
                static readonly int[] Pair = [4, 4, 8];
                static readonly int[] One = [4];
                static readonly int[] OneAgain = [4];
            }
            """, count: 0);
        // Functional code, a generated catalog and other assemblies are outside the rule.
        Expect(Types + "static class DoorScroll { static readonly int[] Frames = [4, 4, 4]; }", count: 0, path: Functional);
        Expect("// <auto-generated/>\n" + Types + "static class DoorDefinitions { static readonly int[] Frames = [4, 4, 4]; }", count: 0);
        Expect(Types + "static class DoorDefinitions { static readonly int[] Frames = [4, 4, 4]; }", count: 0,
            assemblyName: "SuperMetroid.Verification");
        // The import pipeline's definition files hold data too.
        Expect(Types + "static class DoorDefinitions { static readonly int[] Frames = [4, 4, 4]; }",
            "writes the entry '4' out 3 times in a row", assemblyName: RepeatedDefinitionStructureAnalyzer.AssetExtractionAssembly);
    }

    /// <summary>
    /// Compiles one source and compares the SME6483 count; every diagnostic names the catalog's type, and one of them
    /// carries <paramref name="message"/> when it is given.
    /// </summary>
    private static void Expect(string source, string? message = null, int count = 1, string path = Catalog,
        string assemblyName = CoreLayerAnalyzer.CoreAssembly)
    {
        var tree = CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Preview), path: path);
        var compilation = CSharpCompilation.Create(assemblyName, [tree], AnalyzerTests.References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException($"Invalid analyzer fixture: {string.Join("; ", errors.Select(e => e.ToString()))}");
        var diagnostics = compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new RepeatedDefinitionStructureAnalyzer()))
            .GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();
        if (diagnostics.Length != count ||
            diagnostics.Any(d => d.Id != RepeatedDefinitionStructureAnalyzer.RepeatedDefinitionStructureId || d.Severity != DiagnosticSeverity.Error) ||
            !diagnostics.All(d => d.GetMessage().StartsWith("The catalog '", StringComparison.Ordinal)) ||
            (message is not null && !diagnostics.Any(d => d.GetMessage().Contains(message, StringComparison.Ordinal))))
        {
            throw new InvalidOperationException(
                $"Expected {count} {RepeatedDefinitionStructureAnalyzer.RepeatedDefinitionStructureId} diagnostic(s) containing '{message}', " +
                $"got [{string.Join("; ", diagnostics.Select(d => d.ToString()))}] in: {source}");
        }
    }
}
