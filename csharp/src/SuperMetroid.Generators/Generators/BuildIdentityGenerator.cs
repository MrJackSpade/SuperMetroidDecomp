using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SuperMetroid.Generators;

/// <summary>
/// #2602: a build's identity, written at compile time so the game names its builds without reading its own assembly. A
/// compilation that declares <c>static partial class BuildIdentity</c> with the partial properties <c>Guid Version</c> and
/// <c>string InformationalVersion</c> gets their values: the version is the first sixteen bytes of the SHA-256 of the
/// assembly's name and every authored source in compilation order, so it changes exactly when the built code does; the
/// informational version is the compilation's own <c>AssemblyInformationalVersionAttribute</c>, or "unknown" when it
/// declares none; a <c>string AssemblyVersion</c> is the assembly's own version.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class BuildIdentityGenerator : IIncrementalGenerator
{
    private const string ClassName = "BuildIdentity";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<ClassDeclarationSyntax> declarations = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is ClassDeclarationSyntax { Identifier.ValueText: ClassName } declaration &&
                declaration.Modifiers.Any(SyntaxKind.PartialKeyword) && declaration.Modifiers.Any(SyntaxKind.StaticKeyword),
            static (syntax, _) => (ClassDeclarationSyntax)syntax.Node);
        context.RegisterSourceOutput(declarations.Collect().Combine(context.CompilationProvider), static (output, pair) =>
        {
            if (pair.Left.IsDefaultOrEmpty)
                return;
            Compilation compilation = pair.Right;
            var emitted = new HashSet<string>(StringComparer.Ordinal);
            foreach (ClassDeclarationSyntax declaration in pair.Left)
            {
                if (compilation.GetSemanticModel(declaration.SyntaxTree).GetDeclaredSymbol(declaration, output.CancellationToken) is not { } type)
                    continue;
                string name = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                if (!emitted.Add(name))
                    continue;
                output.AddSource($"{type.ToDisplayString()}.g.cs", Emit(type, compilation, output.CancellationToken));
            }
        });
    }

    private static string Emit(INamedTypeSymbol type, Compilation compilation, CancellationToken cancellation)
    {
        var members = new StringBuilder();
        foreach (IPropertySymbol property in type.GetMembers().OfType<IPropertySymbol>())
        {
            if (!property.IsStatic || !property.IsPartialDefinition || property.PartialImplementationPart is not null)
                continue;
            string accessibility = SyntaxFacts.GetText(property.DeclaredAccessibility);
            if (property.Name == "Version" && property.Type.ToDisplayString() == "System.Guid")
                members.Append($"    {accessibility} static partial global::System.Guid Version => new(\"{Version(compilation, cancellation)}\");\n");
            else if (property.Name == "InformationalVersion" && property.Type.SpecialType == SpecialType.System_String)
                members.Append($"    {accessibility} static partial string InformationalVersion => {Literal(InformationalVersion(compilation))};\n");
            else if (property.Name == "AssemblyVersion" && property.Type.SpecialType == SpecialType.System_String)
                members.Append($"    {accessibility} static partial string AssemblyVersion => {Literal(compilation.Assembly.Identity.Version.ToString())};\n");
        }
        string accessibilityOfType = SyntaxFacts.GetText(type.DeclaredAccessibility);
        return $$"""
            // <auto-generated/>
            #nullable enable
            namespace {{type.ContainingNamespace.ToDisplayString()}};

            {{accessibilityOfType}} static partial class {{type.Name}}
            {
            {{members}}}

            """;
    }

    /// <summary>The identity of the compiled code: a hash of the assembly name and every authored source, in compilation order.</summary>
    private static string Version(Compilation compilation, CancellationToken cancellation)
    {
        using var hash = SHA256.Create();
        byte[] name = Encoding.UTF8.GetBytes(compilation.AssemblyName ?? "");
        hash.TransformBlock(name, 0, name.Length, null, 0);
        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            if (GeneratedSource.IsSourceGeneratorOutput(tree, cancellation))
                continue;
            byte[] text = Encoding.UTF8.GetBytes(tree.GetText(cancellation).ToString());
            hash.TransformBlock(text, 0, text.Length, null, 0);
        }
        hash.TransformFinalBlock([], 0, 0);
        byte[] guid = new byte[16];
        Array.Copy(hash.Hash, guid, guid.Length);
        return new Guid(guid).ToString();
    }

    private static string InformationalVersion(Compilation compilation) =>
        compilation.Assembly.GetAttributes()
            .FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Reflection.AssemblyInformationalVersionAttribute")
            ?.ConstructorArguments.FirstOrDefault().Value as string ?? "unknown";

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}
