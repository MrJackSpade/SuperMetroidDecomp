namespace SuperMetroid.Core.Frontend;

/// <summary>
/// Fixed bank-$8B post-credits Samus instruction lists. Idle, gesture, flight,
/// landing, and shooting are one contiguous native program shared by the
/// ending scene, gesture owner, and jump owner.
/// </summary>
