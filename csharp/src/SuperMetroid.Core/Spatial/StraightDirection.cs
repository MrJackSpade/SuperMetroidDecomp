public enum StraightDirection
{
    /// <summary>Straight up the screen.</summary>
    Up,

    /// <summary>Straight right.</summary>
    Right,

    /// <summary>Straight down the screen.</summary>
    Down,

    /// <summary>Straight left.</summary>
    Left,
}
