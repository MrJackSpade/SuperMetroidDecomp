        {
            int a = 0x930000 | entry; ushort value = Word(a);
            words.Add(a);
            if (value == 0x8239) words.Add(a + 2);
            else if (value < 0x8000) words.Add(a + 6);
        }
        AssertEqual(1816, words.Count, "All authored duration/trail/control words inventoried");
        var guard = new ProjectileInstructionReadGuard(rom, words);
        foreach (int a in words)
            AssertEqual(Word(a), SamusProjectileInstructionDefinitions.ReadWord(guard, a), "Compiled instruction word matches cartridge");
        for (int a = 0x938000; a <= 0x93ffff; a++)
            AssertEqual(Word(a), SamusProjectileInstructionDefinitions.ReadWord(rom, a), "Mixed-stream adjacent and unaligned reads preserved");

        var system = new SamusProjectileSystem();
        var bombs = new SamusBombProjectileSystem();
        var runBomb = typeof(SamusBombProjectileSystem).GetMethod("RunProjectileInstructionHandler", BindingFlags.Instance | BindingFlags.NonPublic)!;
        int frames = 0;
        foreach (ushort entry in entries)
        {
            var slot = new SamusProjectileSlot(0) { InstructionPointer = entry, InstructionTimer = 1, Damage = 30 };
            var bomb = new SamusBombProjectileSlot(0) { InstructionPointer = entry, InstructionTimer = 1, Type = 0x0500, Damage = 30 };
            ushort timer = 1, pointer = entry, sprite = 0, x = 0, y = 0, trail = 0;
            for (int frame = 0; frame < 64; frame++)
            {
                bool deleted = false;
                timer = unchecked((ushort)(timer - 1));
                if (timer == 0)
                {
                    int operations = 0;
                    while (true)
                    {
                        AssertTrue(++operations < 16, "Reference stream reaches a frame or delete");
                        int a = 0x930000 | pointer; ushort command = Word(a);
                        if (command == 0x822f) { deleted = true; break; }
                        if (command == 0x8239) { pointer = Word(a + 2); continue; }
                        AssertTrue(command > 0 && command < 0x8000, "Reference timed record valid");
                        timer = command; sprite = Word(a + 2); x = rom.ReadByte(a + 4); y = rom.ReadByte(a + 5);
                        trail = Word(a + 6); pointer = unchecked((ushort)(pointer + 8)); break;
                    }
                }
                AssertEqual(deleted, system.RunProjectileInstructionHandler(guard, slot), "Native delete/timed outcome");
                AssertEqual(deleted, (bool)runBomb.Invoke(bombs, new object[] { guard, bomb })!, "Bomb native delete/timed outcome");
                frames++;
                if (deleted)
                {
                    AssertEqual((ushort)0, slot.Damage, "Delete clears projectile occupancy");
                    AssertEqual((ushort)0, bomb.Type, "Delete clears bomb occupancy");
                    break;
                }
                AssertEqual((timer, pointer, sprite, x, y, trail), (slot.InstructionTimer, slot.InstructionPointer, slot.SpritemapPointer, slot.XRadius, slot.YRadius, slot.AnimationFrame), "Exact projectile frame matches ROM interpreter");
                AssertEqual((timer, pointer, sprite, x, y), (bomb.InstructionTimer, bomb.InstructionPointer, bomb.SpritemapPointer, bomb.XRadius, bomb.YRadius), "Exact bomb frame matches ROM interpreter");
            }
        }
        Console.WriteLine($"Projectile instructions: 1816 native words, {entries.Length} frame/control entries and {frames} frames per owner match independent ROM execution with mechanics reads forbidden.");
    }

    private sealed class ProjectileInstructionReadGuard(ISnesAddressSpace source, HashSet<int> words) : ISnesAddressSpace
    {
        public byte ReadByte(int address)
        {
            if (words.Contains(address) || words.Contains(address - 1))
                throw new InvalidDataException($"Projectile instruction still reads mechanics ROM ${address:X6}.");
            return source.ReadByte(address);
        }
        public void WriteByte(int address, byte value) => source.WriteByte(address, value);
    }
