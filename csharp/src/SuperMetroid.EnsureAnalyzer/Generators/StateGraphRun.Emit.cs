    /// <summary>The scalars a writer and reader name in their methods, by the name each method carries.</summary>
    private static readonly Dictionary<SpecialType, string> Scalars = new()
    {
        [SpecialType.System_Boolean] = "Boolean",
        [SpecialType.System_Byte] = "Byte",
        [SpecialType.System_SByte] = "SByte",
        [SpecialType.System_Int16] = "Int16",
        [SpecialType.System_UInt16] = "UInt16",
        [SpecialType.System_Int32] = "Int32",
        [SpecialType.System_UInt32] = "UInt32",
        [SpecialType.System_Int64] = "Int64",
        [SpecialType.System_UInt64] = "UInt64",
        [SpecialType.System_Char] = "Char",
        [SpecialType.System_Single] = "Single",
        [SpecialType.System_Double] = "Double",
        [SpecialType.System_Decimal] = "Decimal",
    };

    private static string? Scalar(ITypeSymbol type) => Scalars.TryGetValue(type.SpecialType, out string? name) ? name : null;

    private static string WriteValue(ITypeSymbol type, string expression)
    {
        if (Scalar(type) is not null)
            return $"__writer.WriteScalar<{Code(type)}>({expression});";
        if (type.TypeKind == TypeKind.Enum)
            return $"__writer.WriteEnum<{Code(type)}>({expression});";
        return $"__writer.Write((object){expression});";
    }

    private static string ReadValue(ITypeSymbol type)
    {
        if (Scalar(type) is not null)
            return $"__reader.ReadScalar<{Code(type)}>()";
        if (type.TypeKind == TypeKind.Enum)
            return $"__reader.ReadEnum<{Code(type)}>()";
        return $"__reader.Read<{Code(type)}>()";
    }

    /// <summary>Whether a value of the type can hold a reference to another object.</summary>
    internal bool HoldsReferences(ITypeSymbol type, HashSet<ITypeSymbol> visiting)
    {
        if (type.IsReferenceType || type is ITypeParameterSymbol)
            return true;
        if (type.TypeKind is TypeKind.Enum or TypeKind.Pointer or TypeKind.FunctionPointer || Scalar(type) is not null)
            return false;
        if (type is not INamedTypeSymbol named)
            return true;
        if (named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
            return HoldsReferences(named.TypeArguments[0], visiting);
        if (named.SpecialType is SpecialType.System_DateTime or SpecialType.System_IntPtr or SpecialType.System_UIntPtr ||
            named.ToDisplayString() is "System.TimeSpan" or "System.Guid")
            return false;
        if (!visiting.Add(named))
            return false;
        foreach (IFieldSymbol field in named.GetMembers().OfType<IFieldSymbol>())
        {
            if (!field.IsStatic && !field.IsConst && HoldsReferences(field.Type, visiting))
                return true;
        }
        return false;
    }

    /// <summary>
    /// The schema of a value type packed in arrays: its declared name, then each field it writes as name and type, a
    /// nested value type's own schema in place of its type; null when a field is not a scalar, an enum or such a value.
    /// </summary>
    private string? PackedSchema(Level level, HashSet<INamedTypeSymbol> visiting)
    {
        if (level.InlineLength > 0 || !visiting.Add(level.Type))
            return null;
        var schema = new StringBuilder(level.Declared).Append('{');
        if (level.Primary is not null)
        {
            for (int index = 0; index < level.Primary.Parameters.Length; index++)
            {
                if (level.Arguments[index] is null)
                    continue;
                if (PackedType(level.Primary.Parameters[index].Type, visiting) is not { } argument)
                    return null;
                schema.Append('(').Append(level.Primary.Parameters[index].Name).Append("):").Append(argument).Append(';');
            }
        }
        foreach (Member member in level.Restored)
        {
            if (PackedType(member.Type, visiting) is not { } packed)
                return null;
            schema.Append(member.Name).Append(':').Append(packed).Append(';');
        }
        visiting.Remove(level.Type);
        return schema.Append('}').ToString();
    }

    private string? PackedType(ITypeSymbol type, HashSet<INamedTypeSymbol> visiting)
    {
        if (Scalar(type) is not null)
            return type.ToDisplayString();
        if (type.TypeKind == TypeKind.Enum)
            return Declared((INamedTypeSymbol)type);
        // A reference is held as its place in the run's table of the objects its elements hold (#2609).
        // Only a class, array or delegate field: one declared as an interface or object could hold a boxed value instead.
        if (type.TypeKind is TypeKind.Class or TypeKind.Array or TypeKind.Delegate &&
            type.SpecialType is not (SpecialType.System_Object or SpecialType.System_ValueType or SpecialType.System_Enum))
            return "&" + type.ToDisplayString();
        if (type is not INamedTypeSymbol { TypeKind: TypeKind.Struct } named || named.IsGenericType && named.OriginalDefinition.SpecialType != SpecialType.System_Nullable_T)
            return null;
        if (named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
            return PackedType(named.TypeArguments[0], visiting) is { } value ? value + "?" : null;
        if (!SymbolEqualityComparer.Default.Equals(named.ContainingAssembly, compilation.Assembly) || LevelOf(named) is not { } level)
            return null;
        return PackedSchema(level, visiting);
    }

