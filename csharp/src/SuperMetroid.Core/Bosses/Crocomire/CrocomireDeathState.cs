using SuperMetroid.Core.Enemies.Artwork;
namespace SuperMetroid.Core.Bosses.Crocomire;

/// <summary>
/// Typed host projection of Crocomire's non-slot WRAM. The cartridge stores these values in
/// the shared $0688-$069A words, $7E:7800/$8000 extensions, a $0E00-byte melting-graphics
/// buffer, and a 128-byte per-column height table. Keeping that layout out of unrelated empty
/// enemy slots makes the sequence debuggable without changing any of its 16-bit arithmetic.
/// </summary>
public sealed class CrocomireDeathState
{
    /// <summary>Number of height entries used by the melting effect's tile columns.</summary>
    internal const int MeltingColumnCount = 128;
    /// <summary>Graphics scratch capacity including the native off-by-one chunk-copy overlap.</summary>
    /// <remarks>$A4:943D copies $0201 words for each nominal $0200-word chunk; the seventh second-melt chunk reaches beyond the authored $0E00-byte image.</remarks>
    internal const int MeltingGraphicsByteCount = 4608;
    /// <summary>BG2 tilemap words held while Crocomire's melting image is assembled.</summary>
    internal const int Bg2WorkingWordCount = EnemyBg2FrameLayout.TilemapWordCount;

    /// <summary>Per-column erased heights used by the melting progression.</summary>
    internal readonly byte[] MeltingColumnHeights = new byte[MeltingColumnCount];
    /// <summary>Scratch graphics buffer preserving native copy overlap.</summary>
    private readonly byte[] _meltingGraphics = new byte[MeltingGraphicsByteCount];
    /// <summary>BG2 working tilemap used during the death sequence.</summary>
    private readonly ushort[] _bg2WorkingTilemap = new ushort[Bg2WorkingWordCount];
    /// <summary>Per-scanline BG2 vertical offsets generated by melting distortion.</summary>
    private readonly ushort[] _bg2ScrollByScanline = new ushort[256];

    /// <summary>
    /// Bridge fragments the collapse has launched so far, zero through
    /// <see cref="CrocomireBridgeFragmentDefinitions.FragmentCount"/>; it advances once per collapse frame and stops
    /// at the last fragment.
    /// </summary>
    public int BridgeFragmentsSpawned { get; internal set; }

    /// <summary>Six-frame acid smoke cadence at $7E:9018.</summary>
    public NativeCountdown AcidSmokeTimer { get; internal set; }

    /// <summary>Thirty-two-frame acid damage sound cadence (Crocomire var $20).</summary>
    public NativeCountdown AcidSoundTimer { get; internal set; }

    /// <summary>One-shot dust latch for the $0600 bridge approach threshold.</summary>
    public bool BridgeDustAt1536Spawned { get; internal set; }

    /// <summary>One-shot crumble latch for bridge block $61.</summary>
    public bool BridgeBlockAt1568Crumbling { get; internal set; }

    /// <summary>One-shot crumble latch for bridge blocks $62/$63.</summary>
    public bool BridgeBlocksAt1584Crumbling { get; internal set; }

    /// <summary>
    /// Melt-table cursor of the active pass: the pass header before its graphics are copied, the pass's transfer
    /// list while it uploads and dissolves, then the header that follows the pass.
    /// </summary>
    public int MeltingTableOffset { get; internal set; }

    /// <summary>Distance into the active transfer list of the next upload, a multiple of the eight-byte record.</summary>
    public int MeltingTransferOffset { get; internal set; }

    /// <summary>Position in the authored 49-column erase order; it stops one past the last column.</summary>
    public int MeltingColumnCursor { get; internal set; }

    /// <summary>Pixels erased from the selected column in one frame, forty-eight for both passes.</summary>
    public int PixelsToErasePerColumn { get; internal set; }

    /// <summary>Erased height a column must reach before the dissolve moves to the next column.</summary>
    public int MeltTargetHeight { get; internal set; }

    /// <summary>
    /// Skeleton character chunks uploaded so far while the skeleton waits behind the wall; the final sink clears it.
    /// </summary>
    public int SkeletonTileChunk { get; internal set; }

    /// <summary>Lowest BG2 source row the melt distortion stretches back to, from the active pass.</summary>
    public int MaximumAdjustedDestinationY { get; internal set; }

    /// <summary>BG2 source row the distortion starts at; it climbs three rows per frame and stops at sixteen.</summary>
    public int AdjustedDestinationY { get; internal set; }

    /// <summary>
    /// Per-scanline slope of the melt distortion in 1/65536 of a row; it grows from 256 by 384 a frame and stops
    /// at the dissolve's maximum.
    /// </summary>
    public int DistortionStep { get; internal set; }

    /// <summary>Height at which the current distortion band stops, from the active pass.</summary>
    public int DistortionEndY { get; internal set; }

    /// <summary>Body X captured immediately before each melting distortion starts; the melt shake jitters around it.</summary>
    public int BodyXBeforeMelting { get; internal set; }

    /// <summary>
    /// Melt shake counter: decremented once per dissolve frame, wrapping below zero as the cartridge's word does,
    /// and its second bit selects the four-pixel X jitter. The hidden-wall rumble's terminator leaves its own
    /// marker here when the rumble hands the shared word back.
    /// </summary>
    public NativeCountdown MeltShakeCounter { get; internal set; }

    /// <summary>Signed vertical offset in pixels the hidden-wall rumble adds to the foreground scroll.</summary>
    public int RumbleYOffset { get; internal set; }

    /// <summary>Countdown consumed by negative rumble-table entries.</summary>
    public NativeCountdown RumbleCooldown { get; internal set; }

    /// <summary>Pixels per frame the rumble offset moves toward its target, loaded from each completed negative target.</summary>
    public int RumbleDelta { get; internal set; }

    /// <summary>True once $A4:9B86 publishes area-miniboss bit $0002.</summary>
    public bool BossBitSet { get; internal set; }

    /// <summary>True once the skeleton-collapse state invokes the boss item-drop routine.</summary>
    public bool ItemDropRequested { get; internal set; }

    /// <summary>Resultant 256-line BG2 vertical-scroll table used by the melting window.</summary>
    public IReadOnlyList<ushort> Bg2ScrollByScanline => _bg2ScrollByScanline;

    /// <summary>
    /// Whether $A4:9555 has spawned the melting scroll HDMA object and $A4:95CE has
    /// not cleared its channel. Allocated scratch table storage alone does not enable HDMA.
    /// </summary>
    public bool MeltingHdmaActive { get; internal set; }

    /// <summary>Exposes column-height scratch for the active melting update.</summary>
    internal Span<byte> MutableMeltingColumnHeights => MeltingColumnHeights;
    /// <summary>Exposes graphics scratch for native melting copies and tile erasure.</summary>
    internal Span<byte> MutableMeltingGraphics => _meltingGraphics;
    /// <summary>Exposes the BG2 tilemap while death-sequence graphics are assembled.</summary>
    internal Span<ushort> MutableBg2WorkingTilemap => _bg2WorkingTilemap;
    /// <summary>Exposes scanline scroll offsets to the melting distortion writer.</summary>
    internal Span<ushort> MutableBg2ScrollByScanline => _bg2ScrollByScanline;
    /// <summary>Reads the melting graphics scratch without allowing mutation.</summary>
    internal ReadOnlySpan<byte> MeltingGraphics => _meltingGraphics;
    /// <summary>Reads the assembled BG2 tilemap without allowing mutation.</summary>
    internal ReadOnlySpan<ushort> Bg2WorkingTilemap => _bg2WorkingTilemap;
}
