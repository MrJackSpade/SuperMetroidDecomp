    /// <summary>Resolves and enumerates the cartridge pointers of compiled graphics sets.</summary>
    extension(RoomEnemyGraphicsSetDefinitions)
    {
        /// <summary>The compiled graphics set at <paramref name="pointer"/>.</summary>
        internal static RoomEnemyGraphicsSetDefinition Get(ushort pointer) => ByPointer.TryGetValue(pointer, out RoomEnemyGraphicsSetDefinition? found)
            ? found
            : throw new ArgumentOutOfRangeException(nameof(pointer), pointer, "Pointer is not a compiled retail list.");

        /// <summary>The cartridge pointer of <paramref name="definition"/>.</summary>
        internal static ushort PointerOf(RoomEnemyGraphicsSetDefinition definition) =>
            ByPointer.Single(pair => ReferenceEquals(pair.Value, definition)).Key;

        /// <summary>Every compiled pointer, in ascending order.</summary>
        internal static IEnumerable<ushort> Pointers => ByPointer.Keys.Order();
    }
