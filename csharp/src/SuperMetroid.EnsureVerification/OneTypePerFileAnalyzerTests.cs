/// <summary>Checks the #626 one-top-level-type-per-file rule and its code fix.</summary>
internal static class OneTypePerFileAnalyzerTests
{
    /// <summary>Positive and negative cases for SME6400, the fix, then the projects the analyzer cannot analyze itself.</summary>
    internal static void VerifyOneTypePerFileAnalyzer()
    {
        // A second declaration of every type form is reported, naming the file's first type.
        Expect("class A { } class B { }", 1, "'B' is another top-level type in a file that declares 'A' (line 1)");
        Expect("class A { } struct B { }", 1, "'B'");
        Expect("class A { } record B;", 1, "'B'");
        Expect("class A { } record struct B;", 1, "'B'");
        Expect("class A { } record class B;", 1, "'B'");
        Expect("class A { } interface B { }", 1, "'B'");
        Expect("class A { } enum B { X }", 1, "'B'");
        Expect("class A { } delegate void B();", 1, "'B'");
        Expect("enum A { X } delegate void B(); interface C { }", 2);
        // Accessibility, static containers and partial declarations do not change the count.
        Expect("public class A { } internal static class B { } file class C { }", 2);
        Expect("partial class A { } partial class A { }", 1, "'A' is another top-level type in a file that declares 'A'");
        Expect("static class A { extension(int i) { public int Twice => i * 2; } } static class B { }", 1, "'B'");
        // Every namespace form: file-scoped, several blocks, and nested blocks.
        Expect("namespace N;\nclass A { }\nclass B { }", 1, "(line 2)");
        Expect("namespace N1 { class A { } } namespace N2 { class B { } }", 1, "'B'");
        Expect("namespace N { namespace M { class A { } } class B { } }", 1, "'B'");
        // Conditional compilation counts the declarations that are compiled.
        Expect("#if EXTRA\nclass B { }\n#endif\nclass A { }", 0);
        Expect("#if EXTRA\nclass B { }\n#endif\nclass A { }", 1, "'A'", symbols: ["EXTRA"]);
        Expect("#if EXTRA\nclass A { }\n#else\nclass A { }\n#endif", 0, symbols: ["EXTRA"]);
        // Top-level statements own the file: no explicit type may sit beside them.
        Expect("System.Console.WriteLine();", 0, kind: OutputKind.ConsoleApplication);
        Expect("System.Console.WriteLine();\nclass A { }", 1, "beside top-level statements", kind: OutputKind.ConsoleApplication);
        // Repository-generated code is analyzed; only the named framework generators' output is exempt.
        Expect("// <auto-generated/>\nclass A { } class B { }", 1, "'B'");
        Expect("class A { } class B { }", 1, path: "obj/Generated/Repository.g.cs");
        Expect("partial class A { } partial class B { }", 0,
            path: "Microsoft.Interop.LibraryImportGenerator/Microsoft.Interop.LibraryImportGenerator/LibraryImports.g.cs");
        // One type, nested implementation details, and type-free files are legal.
        Expect("class A { }");
        Expect("class A { class Detail { } enum Mode { X } delegate void Callback(); }");
        Expect("[assembly: System.Reflection.AssemblyMetadata(\"k\", \"v\")]\nnamespace N;\nclass A { }");
        Expect("using System;\nnamespace N { }");

        // The fix moves the declaration with its usings, namespace and documentation.
        ExpectFix("using System;\nnamespace N;\n\nclass A { }\n\n/// <summary>B.</summary>\n[Serializable]\nclass B { }\n",
            "using System;\n\nnamespace N;\n\n/// <summary>B.</summary>\n[Serializable]\nclass B { }\n",
            remainingContains: "class A", remainingLacks: "class B");
        ExpectFix("namespace N\n{\n    class A { }\n\n    /// <summary>B.</summary>\n    class B\n    {\n        int x;\n    }\n}\n",
            "namespace N;\n\n/// <summary>B.</summary>\nclass B\n{\n    int x;\n}\n",
            remainingContains: "class A", remainingLacks: "class B");
        // Directives, statements, file-local types and a name the file already uses need manual placement.
        ExpectFix("#if DEBUG\nclass A { }\n#endif\nclass B { }\nclass C { }\n", null, symbols: ["DEBUG"]);
        ExpectFix("System.Console.WriteLine();\nclass A { }\n", null, kind: OutputKind.ConsoleApplication);
        ExpectFix("class A { }\nfile class B { }\n", null);
        ExpectFix("partial class A { }\npartial class A { }\n", null);

        // SME6401: the file is named after its type; a partial part may add its purpose.
        ExpectName("class Widget { }", "Widget.cs", 0);
        ExpectName("class Widget<T> { }", "Widget.cs", 0);
        ExpectName("namespace N;\nenum Mode { A }", "Mode.cs", 0);
        ExpectName("partial class Widget { }", "Widget.Drawing.cs", 0);
        ExpectName("delegate void Callback();", "Callback.cs", 0);
        ExpectName("class Widget { }", "Widgets.cs", 1, "'Widget' is declared in 'Widgets.cs'; name the file 'Widget.cs'");
        ExpectName("class Widget { }", "Widget.Drawing.cs", 1, "'Widget' is declared in 'Widget.Drawing.cs'");
        ExpectName("partial class Widget { }", "Program.Widget.cs", 1, "or 'Widget.<Purpose>.cs' for this partial part");
        ExpectName("partial class Widget { }", "Widget..cs", 1);
        ExpectName("enum Mode { A }", "ModeCodes.cs", 1, "'Mode'");
        // Files without a type, several types (SME6400's report) and framework generator output are not named here.
        ExpectName("[assembly: System.Reflection.AssemblyMetadata(\"k\", \"v\")]", "AssemblyInfo.cs", 0);
        ExpectName("System.Console.WriteLine();", "Program.cs", 0, kind: OutputKind.ConsoleApplication);
        ExpectName("class A { } class B { }", "Pair.cs", 0);
        ExpectName("partial class A { }", "Microsoft.Interop.LibraryImportGenerator/Microsoft.Interop.LibraryImportGenerator/LibraryImports.g.cs", 0);
        ExpectName("public class Resource { }", "obj/Release/net10.0-android/__Microsoft.Android.Resource.Designer.cs", 0);

        VerifyAnalyzerProjectsDeclareOneTypePerFile();
        Console.WriteLine("#626 one type per file: SME6400 reports every extra top-level type in all forms; the fix moves unambiguous declarations.");
    }

    /// <summary>The analyzer projects and this verifier do not load the analyzer they build, so their sources are checked here.</summary>
    private static void VerifyAnalyzerProjectsDeclareOneTypePerFile()
    {
        string source = NullForgivingAnalyzerTests.SourceDirectory();
        string csharp = Path.GetDirectoryName(source) ?? throw new DirectoryNotFoundException(source);
        ModuleMap map = ModuleMap.Parse(File.ReadAllText(Path.Combine(csharp, ModuleMap.FileName)),
            Path.GetDirectoryName(csharp) ?? throw new DirectoryNotFoundException(csharp));
        foreach (string project in new[] { "SuperMetroid.EnsureAnalyzer", "SuperMetroid.EnsureAnalyzer.CodeFixes", "SuperMetroid.EnsureVerification" })
        {
            foreach (string file in Directory.EnumerateFiles(Path.Combine(source, project), "*.cs", SearchOption.AllDirectories))
            {
                string normalized = file.Replace('\\', '/');
                if (normalized.Contains("/bin/") || normalized.Contains("/obj/"))
                    continue;
                var root = (CompilationUnitSyntax)CSharpSyntaxTree.ParseText(File.ReadAllText(file), new CSharpParseOptions(LanguageVersion.Preview), file).GetRoot();
                var types = OneTypePerFileAnalyzer.TopLevelTypes(root);
                if (types.Length > 1)
                {
                    throw new InvalidOperationException(
                        $"{file}: declares {string.Join(", ", types.Select(OneTypePerFileAnalyzer.NameOf))}; one top-level type per file (SME6400).");
                }
                if (types.Length == 1 && !TypeFileNameAnalyzer.NamesType(Path.GetFileNameWithoutExtension(file), types[0]))
                    throw new InvalidOperationException($"{file}: declares {OneTypePerFileAnalyzer.NameOf(types[0])}; name the file after it (SME6401).");
                if (types.Length == 1 && map.Relative(file) is { } relative && map.ModuleOf(relative) is { } module)
                {
                    string declared = root.DescendantNodes().OfType<BaseNamespaceDeclarationSyntax>().FirstOrDefault()?.Name.ToString() ?? "";
                    string expected = ModuleMap.ExpectedNamespace(module, relative);
                    if (declared != expected)
                        throw new InvalidOperationException($"{file}: declares namespace '{declared}'; its module path implies '{expected}' (SME6402).");
                }
                else if (types.Length == 1)
                {
                    throw new InvalidOperationException($"{file}: is not inside a module registered in csharp/module-map.json (SME6403).");
                }
            }
        }
    }

    /// <summary>Compiles one source and compares the SME6400 count and an optional message fragment.</summary>
    private static void Expect(string source, int count = 0, string? message = null, string[]? symbols = null,
        OutputKind kind = OutputKind.DynamicallyLinkedLibrary, string path = "Case.cs")
    {
        var tree = CSharpSyntaxTree.ParseText(source, Parse(symbols), path: path);
        var compilation = CSharpCompilation.Create("OneTypeCase", [tree], AnalyzerTests.References,
            new CSharpCompilationOptions(kind, nullableContextOptions: NullableContextOptions.Enable));
        var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException($"Invalid one-type fixture: {string.Join("; ", errors.Select(e => e.ToString()))} in: {source}");
        var diagnostics = compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new OneTypePerFileAnalyzer()))
            .GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();
        if (diagnostics.Length != count || diagnostics.Any(d => d.Id != OneTypePerFileAnalyzer.Id || d.Severity != DiagnosticSeverity.Error) ||
            (message is not null && !diagnostics.All(d => d.GetMessage().Contains(message, StringComparison.Ordinal))))
        {
            throw new InvalidOperationException(
                $"Expected {count} {OneTypePerFileAnalyzer.Id} diagnostic(s) containing '{message}', got [{string.Join("; ", diagnostics.Select(d => d.ToString()))}] in: {source}");
        }
    }

    /// <summary>Compiles one source at <paramref name="path"/> and compares the SME6401 count and message fragment.</summary>
    private static void ExpectName(string source, string path, int count, string? message = null, OutputKind kind = OutputKind.DynamicallyLinkedLibrary)
    {
        var tree = CSharpSyntaxTree.ParseText(source, Parse(null), path: path);
        var compilation = CSharpCompilation.Create("FileNameCase", [tree], AnalyzerTests.References,
            new CSharpCompilationOptions(kind, nullableContextOptions: NullableContextOptions.Enable));
        var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException($"Invalid file-name fixture: {string.Join("; ", errors.Select(e => e.ToString()))} in: {source}");
        var diagnostics = compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new TypeFileNameAnalyzer()))
            .GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();
        if (diagnostics.Length != count || diagnostics.Any(d => d.Id != TypeFileNameAnalyzer.Id || d.Severity != DiagnosticSeverity.Error) ||
            (message is not null && !diagnostics.All(d => d.GetMessage().Contains(message, StringComparison.Ordinal))))
        {
            throw new InvalidOperationException(
                $"Expected {count} {TypeFileNameAnalyzer.Id} diagnostic(s) containing '{message}' for {path}, got [{string.Join("; ", diagnostics.Select(d => d.GetMessage()))}] in: {source}");
        }
    }

    /// <summary>Applies the fix for the first diagnostic and compares the new file, or checks that no fix is offered.</summary>
    private static void ExpectFix(string source, string? expectedNewFile, string? remainingContains = null, string? remainingLacks = null,
        string[]? symbols = null, OutputKind kind = OutputKind.DynamicallyLinkedLibrary)
    {
        using var workspace = new AdhocWorkspace();
        string directory = Path.Combine(Path.GetTempPath(), "sme6400-fix-" + Guid.NewGuid().ToString("N"));
        Project project = workspace.AddProject("OneTypeFixCase", LanguageNames.CSharp)
            .WithCompilationOptions(new CSharpCompilationOptions(kind, nullableContextOptions: NullableContextOptions.Enable))
            .WithParseOptions(Parse(symbols))
            .WithMetadataReferences(AnalyzerTests.References);
        Document document = project.AddDocument("Case.cs", SourceText.From(source), filePath: Path.Combine(directory, "Case.cs"));
        Compilation compilation = document.Project.GetCompilationAsync().GetAwaiter().GetResult() ??
            throw new InvalidOperationException("One-type fix fixture produced no compilation.");
        Diagnostic diagnostic = compilation.WithAnalyzers([new OneTypePerFileAnalyzer()])
            .GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult().First();
        var actions = new List<CodeAction>();
        new OneTypePerFileCodeFixProvider().RegisterCodeFixesAsync(
            new CodeFixContext(document, diagnostic, (action, _) => actions.Add(action), CancellationToken.None)).GetAwaiter().GetResult();
        if (expectedNewFile is null)
        {
            if (actions.Count != 0)
                throw new InvalidOperationException($"Unexpected one-type fix '{actions[0].Title}' for: {source}");
            return;
        }
        if (actions.Count != 1)
            throw new InvalidOperationException($"Expected one one-type fix, got {actions.Count} for: {source}");
        Solution changed = actions[0].GetOperationsAsync(CancellationToken.None).GetAwaiter().GetResult()
            .OfType<ApplyChangesOperation>().Single().ChangedSolution;
        Project fixedProject = changed.GetProject(project.Id) ?? throw new InvalidOperationException("The fix removed the project.");
        Document added = fixedProject.Documents.Single(d => d.Id != document.Id);
        string addedText = added.GetTextAsync().GetAwaiter().GetResult().ToString();
        if (addedText != expectedNewFile || added.FilePath != Path.Combine(directory, "B.cs"))
            throw new InvalidOperationException($"One-type fix wrote {added.FilePath}:\n{addedText}\nexpected B.cs:\n{expectedNewFile}");
        string remaining = (fixedProject.GetDocument(document.Id) ?? throw new InvalidOperationException("The fix removed the original."))
            .GetTextAsync().GetAwaiter().GetResult().ToString();
        if ((remainingContains is not null && !remaining.Contains(remainingContains, StringComparison.Ordinal)) ||
            (remainingLacks is not null && remaining.Contains(remainingLacks, StringComparison.Ordinal)))
            throw new InvalidOperationException($"One-type fix left:\n{remaining}");
        Compilation after = fixedProject.GetCompilationAsync().GetAwaiter().GetResult() ??
            throw new InvalidOperationException("The fixed project produced no compilation.");
        var errors = after.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException($"The fixed project does not compile: {string.Join("; ", errors.Select(e => e.ToString()))}");
    }

    /// <summary>Preview parse options with the given preprocessor symbols.</summary>
    private static CSharpParseOptions Parse(string[]? symbols) =>
        new(LanguageVersion.Preview, DocumentationMode.Diagnose, preprocessorSymbols: symbols ?? []);
}
