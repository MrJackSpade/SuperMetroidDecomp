using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SuperMetroid.EnsureAnalyzer.Generators;

/// <summary>
/// #2602: a text file the assembly carries, written into the assembly by the compiler so the code reads it without looking
/// up a resource by name. A static partial string property carrying <c>[GeneratedText("file name")]</c> is implemented as
/// the text of the project's additional file of that name, which must be present exactly once.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class GeneratedTextGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor Missing = new("SME6490", "Generated text file missing",
        "No additional file named '{0}' supplies the text of {1}, or more than one does", "Build", DiagnosticSeverity.Error, isEnabledByDefault: true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<PropertyDeclarationSyntax> properties = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is PropertyDeclarationSyntax property && property.Modifiers.Any(SyntaxKind.PartialKeyword) &&
                property.AttributeLists.SelectMany(list => list.Attributes).Any(attribute => attribute.Name.ToString() is "GeneratedText" or "GeneratedTextAttribute"),
            static (syntax, _) => (PropertyDeclarationSyntax)syntax.Node);
        var inputs = properties.Collect().Combine(context.AdditionalTextsProvider.Collect()).Combine(context.CompilationProvider);
        context.RegisterSourceOutput(inputs, static (output, input) =>
        {
            ((var declarations, var files), Compilation compilation) = input;
            foreach (PropertyDeclarationSyntax declaration in declarations)
            {
                if (compilation.GetSemanticModel(declaration.SyntaxTree).GetDeclaredSymbol(declaration, output.CancellationToken) is not IPropertySymbol property ||
                    !property.IsPartialDefinition || property.PartialImplementationPart is not null)
                    continue;
                AttributeData? attribute = property.GetAttributes().FirstOrDefault(data => data.AttributeClass?.Name == "GeneratedTextAttribute");
                if (attribute?.ConstructorArguments.FirstOrDefault().Value is not string name)
                    continue;
                AdditionalText[] matching = [.. files.Where(file => string.Equals(Path.GetFileName(file.Path), name, StringComparison.Ordinal))];
                if (matching.Length != 1 || matching[0].GetText(output.CancellationToken) is not { } text)
                {
                    output.ReportDiagnostic(Diagnostic.Create(Missing, declaration.GetLocation(), name, property.Name));
                    continue;
                }
                output.AddSource($"{property.ContainingType.ToDisplayString()}.{property.Name}.g.cs", Emit(property, text.ToString()));
            }
        });
    }

    private static string Emit(IPropertySymbol property, string text)
    {
        INamedTypeSymbol type = property.ContainingType;
        var opening = new StringBuilder();
        var closing = new StringBuilder();
        var chain = new Stack<INamedTypeSymbol>();
        for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
            chain.Push(current);
        foreach (INamedTypeSymbol current in chain)
        {
            opening.Append($"{SyntaxFacts.GetText(current.DeclaredAccessibility)} {(current.IsStatic ? "static " : "")}partial class {current.Name}\n{{\n");
            closing.Append("}\n");
        }
        return $$"""
            // <auto-generated/>
            #nullable enable
            namespace {{type.ContainingNamespace.ToDisplayString()}};

            {{opening}}    {{SyntaxFacts.GetText(property.DeclaredAccessibility)}} static partial string {{property.Name}} => {{SymbolDisplay.FormatLiteral(text, quote: true)}};
            {{closing}}
            """;
    }
}
