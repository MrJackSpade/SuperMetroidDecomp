namespace SuperMetroid.Core.Rooms.Doors;

/// <summary>The paint a door cap's closed images show: the blue cap, the grey cap, or a yellow, green or red cap.</summary>
internal enum DoorCapPaint
{
    /// <summary>The blue cap any shot opens.</summary>
    Blue,
    /// <summary>The grey cap a condition locks.</summary>
    Grey,
    /// <summary>The yellow cap a Power Bomb opens.</summary>
    Yellow,
    /// <summary>The green cap a Super Missile opens.</summary>
    Green,
    /// <summary>The red cap missiles open.</summary>
    Red,
}
