{
    /// <summary>$8B:ED1D, first suitless idle instruction.</summary>
    internal const ushort Start = 0xed1d;
    /// <summary>$8B:EE5D, exclusive end after both suited head-flight lists.</summary>
    internal const ushort End = 0xee5d;

    private static ReadOnlySpan<ushort> Program =>
    [
        // Suitless idle, hair-down gesture, jump, landing, and shot.
        0x0080, 0x9ff7, 0x94bc, 0xed1d, 0x0080, 0xa243, 0x94bc, 0xed25,
