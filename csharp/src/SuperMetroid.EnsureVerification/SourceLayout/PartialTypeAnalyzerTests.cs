using SuperMetroid.EnsureVerification.CartridgeEncoding;
using Microsoft.CodeAnalysis.Diagnostics;
using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using SuperMetroid.EnsureAnalyzer.SourceLayout;
using SuperMetroid.EnsureVerification.Harness;

namespace SuperMetroid.EnsureVerification.SourceLayout;

/// <summary>Checks partial-type diagnostics against handwritten and generated declaration pairs.</summary>
internal static class PartialTypeAnalyzerTests
{
    /// <summary>#621 partial-type rules: positive and negative cases for each diagnostic.</summary>
    internal static void VerifyPartialTypeAnalyzer()
    {
        const string header = "// <auto-generated>\n//     Generated by a checked-in generator.\n// </auto-generated>\n";

        // SME6360: hand-written code split across declarations, in one file or several, reported at each.
        Expect([new AnalyzerTestSource("A.cs", "partial class C { void M() { } }"), new AnalyzerTestSource("A.More.cs", "partial class C { void N() { } }")],
            PartialTypeAnalyzer.SplitId, 2, "C has 2 hand-written partial declarations");
        Expect([new AnalyzerTestSource("A.cs", "partial class C { } partial class C { }")], PartialTypeAnalyzer.SplitId, 2);
        Expect([new AnalyzerTestSource("A.cs", "partial struct S { }"), new AnalyzerTestSource("B.cs", "partial struct S { }")], PartialTypeAnalyzer.SplitId, 2);
        Expect([new AnalyzerTestSource("A.cs", "partial record R { }"), new AnalyzerTestSource("B.cs", "partial record R { }")], PartialTypeAnalyzer.SplitId, 2);
        Expect([new AnalyzerTestSource("A.cs", "class O { partial class N { } partial class N { } }")], PartialTypeAnalyzer.SplitId, 2, "O.N");
        // A generated half does not excuse a second hand-written one.
        Expect([new AnalyzerTestSource("A.cs", "partial class C { }"), new AnalyzerTestSource("A.More.cs", "partial class C { }"), new AnalyzerTestSource("A.Generated.cs", "partial class C { }")],
            PartialTypeAnalyzer.SplitId, 2);

        // SME6361: partial with nothing generated to complete it.
        Expect([new AnalyzerTestSource("A.cs", "partial class C { }")], PartialTypeAnalyzer.UngeneratedId, 1, "C is partial but no generated declaration");
        Expect([new AnalyzerTestSource("A.cs", "static partial class C { static void M() { } }")], PartialTypeAnalyzer.UngeneratedId, 1);
        // A comment that merely mentions generation is not the compiler's header convention.
        Expect([new AnalyzerTestSource("A.cs", "partial class C { }"), new AnalyzerTestSource("B.cs", "// Generated from the cartridge.\npartial class C { }")],
            PartialTypeAnalyzer.SplitId, 2);

        // Allowed: one hand-written declaration plus generated ones, recognized by file name or header.
        Expect([new AnalyzerTestSource("Definitions.cs", "partial class C { }"), new AnalyzerTestSource("Definitions.Generated.cs", "partial class C { int X => 1; }")]);
        Expect([new AnalyzerTestSource("Definitions.cs", "partial class C { }"), new AnalyzerTestSource("Bank86.cs", header + "partial class C { int X => 1; }")]);
        Expect([new AnalyzerTestSource("Definitions.cs", "partial class C { }"), new AnalyzerTestSource("obj/LibraryImports.g.cs", "partial class C { }")]);
        Expect([new AnalyzerTestSource("Form.cs", "partial class F { }"), new AnalyzerTestSource("Form.Designer.cs", "partial class F { }")]);
        Expect([new AnalyzerTestSource("Many.cs", "partial class C { }"), new AnalyzerTestSource("B1.Generated.cs", "partial class C { }"), new AnalyzerTestSource("B2.Generated.cs", "partial class C { }")]);
        // A nested generated boundary: the generator completes both the nested type and its container.
        Expect([new AnalyzerTestSource("Device.cs", "partial class D { static partial class Native { } }"),
            new AnalyzerTestSource("obj/LibraryImports.g.cs", "partial class D { static partial class Native { } }")]);
        // Ordinary and wholly generated types are not this rule's concern.
        Expect([new AnalyzerTestSource("A.cs", "class C { } sealed class D { }")]);
        Expect([new AnalyzerTestSource("Only.Generated.cs", "partial class C { }"), new AnalyzerTestSource("Other.Generated.cs", "partial class C { }")]);
    }

    /// <summary>Compiles a small source set and compares diagnostic ID, severity, count, and optional text.</summary>
    private static void Expect(AnalyzerTestSource[] files, string? id = null, int count = 0, string? message = null)
    {
        var trees = files.Select(file => CSharpSyntaxTree.ParseText(file.Source,
            new CSharpParseOptions(LanguageVersion.Preview), path: file.Path)).ToArray();
        var compilation = CSharpCompilation.Create("PartialTypeCase", trees, AnalyzerTests.References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException($"Invalid analyzer fixture: {string.Join("; ", errors.Select(e => e.ToString()))}");
        var diagnostics = compilation.WithAnalyzers(ImmutableArray.Create<Microsoft.CodeAnalysis.Diagnostics.DiagnosticAnalyzer>(
            new PartialTypeAnalyzer())).GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();
        string described = string.Join(" | ", files.Select(file => $"{file.Path}: {file.Source}"));
        if (id is null)
        {
            if (diagnostics.Length != 0)
                throw new InvalidOperationException($"Unexpected analyzer diagnostic: {diagnostics[0]} in {described}");
            return;
        }
        if (diagnostics.Length != count || diagnostics.Any(d => d.Id != id || d.Severity != DiagnosticSeverity.Error) ||
            (message is not null && !diagnostics.All(d => d.GetMessage().Contains(message, StringComparison.Ordinal))))
        {
            throw new InvalidOperationException(
                $"Expected {count} {id} diagnostic(s) containing '{message}', got [{string.Join("; ", diagnostics.Select(d => d.ToString()))}] in {described}");
        }
    }
}
