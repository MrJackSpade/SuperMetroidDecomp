using System.Text;
using SuperMetroid.AssetExtraction;
using SuperMetroid.Core.Progression;
using SuperMetroid.Core.Rooms.LevelData;

namespace SuperMetroid.DebugRunner.Tools;

/// <summary>
/// Generates the kept block behaviours (#1722, #1805), <c>RoomBlockReadingDefinitions.Generated.cs</c>: the import codec's
/// decoding of every behaviour byte under every collision kind, in the byte's order, and of each byte whose meaning to
/// special blocks and special air the areas give, in every area, so the runtime holds every reading by name and no byte.
/// </summary>
internal static class RoomBlockReadingGenerator
{
    /// <summary>The generated catalog, relative to the repository root.</summary>
    internal const string GeneratedPath = "csharp/src/SuperMetroid.Core/Rooms/LevelData/RoomBlockReadingDefinitions.Generated.cs";

    /// <summary>Writes the catalog over the checked-in one; the codec is its only source.</summary>
    internal static int Generate()
    {
        File.WriteAllText(GeneratedPath, Render(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        Console.WriteLine($"Generated {RoomBlockBehaviorCodec.ByteCount} kept block behaviours at {GeneratedPath}.");
        return 0;
    }

    /// <summary>The catalog's source text.</summary>
    internal static string Render()
    {
        var text = new StringBuilder();
        text.Append("// <auto-generated/>\n");
        text.Append("using SuperMetroid.Core.Progression;\n\n");
        text.Append("namespace SuperMetroid.Core.Rooms.LevelData;\n\n");
        text.Append("/// <summary>\n");
        text.Append("/// Every behaviour a block can keep, each holding every collision kind's reading of it, in the order the game numbers them\n");
        text.Append("/// (#1722): a write of a reading keeps the first holding it (<see cref=\"SuperMetroid.Core.Compatibility.BlockParameterCarryOver{TBehavior, TReading}\"/>).\n");
        text.Append("/// A behaviour whose meaning to special blocks and special air the room's area gives holds neither reading, and each area's\n");
        text.Append("/// meaning is its own reaction (<see cref=\"InAreas\"/>, #1805).\n");
        text.Append("/// Regenerate with <c>SuperMetroid.DebugRunner --generate-room-block-readings</c> from the import codec.\n");
        text.Append("/// </summary>\n");
        text.Append("internal static class RoomBlockReadingDefinitions\n{\n");
        text.Append("    /// <summary>Every kept behaviour.</summary>\n");
        text.Append("    internal static readonly IReadOnlyList<RoomBlockReadings> Kept =\n    [\n");
        for (int value = 0; value < RoomBlockBehaviorCodec.ByteCount; value++)
            text.Append("        ").Append(Readings(RoomBlockBehaviorCodec.ReadingsOf(value), "            ")).Append(",\n");
        text.Append("    ];\n\n");
        text.Append("    /// <summary>\n");
        text.Append("    /// Each kept behaviour whose meaning to special blocks and special air the room's area gives, as each group of areas\n");
        text.Append("    /// resolves it, in the order of <see cref=\"Kept\"/> and then the game's area order.\n");
        text.Append("    /// </summary>\n");
        text.Append("    internal static readonly IReadOnlyList<AreaBlockReadings> InAreas =\n    [\n");
        for (int value = 0; value < RoomBlockBehaviorCodec.ByteCount; value++)
        {
            List<(AreaId Area, RoomBlockReadings Readings)> inAreas =
                [.. AreaIds.All.Select(area => (area, RoomBlockBehaviorCodec.ReadingsOf(area, value)))];
            if (inAreas.Select(resolution => resolution.Readings).Distinct().Count() == 1)
                continue;
            foreach (IGrouping<RoomBlockReadings, AreaId> resolution in inAreas.GroupBy(item => item.Readings, item => item.Area))
            {
                text.Append("        new([").Append(string.Join(", ", resolution.Select(area => $"AreaId.{area}"))).Append("], ")
                    .Append(Readings(resolution.Key, "            ")).Append("),\n");
            }
        }
        text.Append("    ];\n}\n");
        return text.ToString();
    }

    /// <summary>One kept behaviour's source, its slope, extension and door readings on a second line at <paramref name="indent"/>.</summary>
    private static string Readings(RoomBlockReadings readings, string indent) => new StringBuilder()
        .Append("new(")
        .Append(Reaction(readings.Shootable)).Append(", ")
        .Append(Reaction(readings.Bombable)).Append(", ")
        .Append(Reaction(readings.Special)).Append(", ")
        .Append(Reaction(readings.SpecialAir)).Append(", ")
        .Append(Reaction(readings.Spike)).Append(", ")
        .Append(Reaction(readings.Grapple)).Append(",\n").Append(indent)
        .Append("new(SlopeShapeDefinitions.").Append(readings.Slope.Shape.Name).Append(", BlockMirroring.").Append(readings.Slope.Mirroring).Append("), ")
        .Append(readings.ExtensionOffset).Append(", ").Append(readings.DoorLink).Append(')')
        .ToString();

    /// <summary>A reading's source: the reaction by its type and name, or null for a kind with no reaction (#1742).</summary>
    private static string Reaction<TReaction>(TReaction? reaction)
        where TReaction : struct, Enum =>
        reaction is { } named ? $"{typeof(TReaction).Name}.{named}" : "null";
}
