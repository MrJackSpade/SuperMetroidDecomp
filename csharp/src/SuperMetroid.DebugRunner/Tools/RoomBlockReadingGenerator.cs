using System.Text;
using SuperMetroid.AssetExtraction;
using SuperMetroid.Core.Progression;
using SuperMetroid.Core.Rooms.LevelData;

namespace SuperMetroid.DebugRunner.Tools;

/// <summary>
/// Generates the kept block behaviours (#1722, #1805, #2556), <c>RoomBlockReadingDefinitions.cs</c>: for each collision kind's
/// reading, the behaviour a write of it keeps, every reading of that behaviour written out, and each behaviour whose meaning
/// to special blocks and special air the areas give, in every area. Which behaviour a write keeps is the import codec's
/// knowledge: the game writes a reading as the first byte holding it, each byte followed by its areas' resolutions, so the
/// generator decides each write here and the runtime holds every reading by name and no byte, and reads no order.
/// </summary>
internal static class RoomBlockReadingGenerator
{
    /// <summary>The generated catalog, relative to the repository root.</summary>
    internal const string GeneratedPath = "csharp/src/SuperMetroid.Core/Rooms/LevelData/RoomBlockReadingDefinitions.cs";

    /// <summary>The indent of a written behaviour's second line.</summary>
    private const string ContinuationIndent = "            ";

    /// <summary>Writes the catalog over the checked-in one; the codec is its only source.</summary>
    internal static int Generate()
    {
        File.WriteAllText(GeneratedPath, Render(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        Console.WriteLine($"Generated the behaviours {RoomBlockBehaviorCodec.ByteCount} behaviour bytes keep at {GeneratedPath}.");
        return 0;
    }

    /// <summary>The catalog's source text.</summary>
    internal static string Render()
    {
        List<AreaResolutionGroup> inAreas = AreaResolutions();
        List<RoomBlockReadings> precedence = WritePrecedence(inAreas);
        var text = new StringBuilder();
        text.Append("// <auto-generated/>\n");
        text.Append("using SuperMetroid.Core.Progression;\n\n");
        text.Append("namespace SuperMetroid.Core.Rooms.LevelData;\n\n");
        text.Append("/// <summary>\n");
        text.Append("/// The behaviour a block keeps when it is written as each collision kind's reading (#1722, #2556): each kind's table names,\n");
        text.Append("/// for every reading the kind can be written as, every reading of the behaviour the write keeps, so a later change of the\n");
        text.Append("/// block's collision kind reads what the game reads (<see cref=\"SuperMetroid.Core.Compatibility.BlockParameterCarryOver{TBehavior, TReading}\"/>).\n");
        text.Append("/// Which behaviour a write keeps is the import codec's knowledge of the game's own writes, decided by the generator and\n");
        text.Append("/// written out here; nothing reads a table's order. A behaviour whose meaning to special blocks and special air the room's\n");
        text.Append("/// area gives holds neither reading, and each area's meaning is its own reaction (<see cref=\"InAreas\"/>, #1805).\n");
        text.Append("/// Regenerate with <c>SuperMetroid.DebugRunner --generate-room-block-readings</c> from the import codec.\n");
        text.Append("/// </summary>\n");
        text.Append("internal static class RoomBlockReadingDefinitions\n{\n");
        AppendTable<ShootableReaction>(text, "Shootable", "shootable reaction", "ShootableReaction", precedence, static readings => readings.Shootable, Named);
        AppendTable<BombableReaction>(text, "Bombable", "bombable reaction", "BombableReaction", precedence, static readings => readings.Bombable, Named);
        AppendTable<SpecialBlockReaction>(text, "Special", "special-block reaction", "SpecialBlockReaction", precedence, static readings => readings.Special, Named);
        AppendTable<SpecialAirReaction>(text, "SpecialAir", "special-air reaction", "SpecialAirReaction", precedence, static readings => readings.SpecialAir, Named);
        AppendTable<SpikeReaction>(text, "Spike", "spike reaction", "SpikeReaction", precedence, static readings => readings.Spike, Named);
        AppendTable<GrappleReaction>(text, "Grapple", "grapple reaction", "GrappleReaction", precedence, static readings => readings.Grapple, Named);
        AppendTable<SlopeGeometry>(text, "Slope", "slope shape and mirroring", "SlopeGeometry", precedence, static readings => readings.Slope, Slope);
        AppendTable<int>(text, "Extension", "extension offset", "int", [.. precedence.OrderBy(static readings => readings.ExtensionOffset)],
            static readings => readings.ExtensionOffset, static offset => offset.ToString(System.Globalization.CultureInfo.InvariantCulture));
        text.Append("    /// <summary>\n");
        text.Append("    /// Each behaviour whose meaning to special blocks and special air the room's area gives, as each group of areas resolves\n");
        text.Append("    /// it: the behaviour, named by the extension write that keeps it, and the two meanings those areas give it.\n");
        text.Append("    /// </summary>\n");
        text.Append("    internal static readonly IReadOnlyList<AreaBlockReadings> InAreas =\n    [\n");
        foreach (AreaResolutionGroup resolution in inAreas)
        {
            text.Append("        new([").Append(string.Join(", ", resolution.Areas.Select(area => $"AreaId.{area}"))).Append("], ")
                .Append("Extension[").Append(resolution.Readings.ExtensionOffset.ToString(System.Globalization.CultureInfo.InvariantCulture)).Append("], ")
                .Append(Named(resolution.Readings.Special ?? throw new InvalidOperationException($"An area leaves byte {resolution.Value}'s special-block meaning out.")))
                .Append(", ")
                .Append(Named(resolution.Readings.SpecialAir ?? throw new InvalidOperationException($"An area leaves byte {resolution.Value}'s special-air meaning out.")))
                .Append("),\n");
        }
        text.Append("    ];\n}\n");
        return text.ToString();
    }

    /// <summary>One group of areas resolving a byte's special-block and special-air meaning the same way.</summary>
    /// <param name="Value">The byte.</param>
    /// <param name="Areas">The areas, in the game's area order.</param>
    /// <param name="Readings">Every reading of the byte in those areas.</param>
    private sealed record AreaResolutionGroup(int Value, IReadOnlyList<AreaId> Areas, RoomBlockReadings Readings);

    /// <summary>Each byte the areas resolve differently, as each group of areas resolves it, in the byte's and the areas' order.</summary>
    private static List<AreaResolutionGroup> AreaResolutions()
    {
        var groups = new List<AreaResolutionGroup>();
        for (int value = 0; value < RoomBlockBehaviorCodec.ByteCount; value++)
        {
            List<(AreaId Area, RoomBlockReadings Readings)> inAreas =
                [.. AreaIds.All.Select(area => (area, RoomBlockBehaviorCodec.ReadingsOf(area, value)))];
            if (inAreas.Select(resolution => resolution.Readings).Distinct().Count() == 1)
                continue;
            foreach (IGrouping<RoomBlockReadings, AreaId> resolution in inAreas.GroupBy(item => item.Readings, item => item.Area))
                groups.Add(new AreaResolutionGroup(value, [.. resolution], resolution.Key));
        }
        return groups;
    }

    /// <summary>
    /// Every behaviour in the order the game's writes prefer them: each byte's behaviour in any area followed by its areas'
    /// resolutions, so a write of a reading keeps the first holding it, the byte the game's own writes of that reading store.
    /// </summary>
    private static List<RoomBlockReadings> WritePrecedence(List<AreaResolutionGroup> inAreas)
    {
        var precedence = new List<RoomBlockReadings>();
        for (int value = 0; value < RoomBlockBehaviorCodec.ByteCount; value++)
        {
            precedence.Add(RoomBlockBehaviorCodec.ReadingsOf(value));
            int resolved = value;
            precedence.AddRange(inAreas.Where(resolution => resolution.Value == resolved).Select(static resolution => resolution.Readings));
        }
        return precedence;
    }

    /// <summary>
    /// Writes one kind's table: each reading the kind can be written as, keyed by itself, with every reading of the first
    /// behaviour in <paramref name="precedence"/> holding it; a kind with no reaction for a behaviour is never written as it.
    /// </summary>
    private static void AppendTable<TReading>(StringBuilder text, string name, string description, string readingType,
        List<RoomBlockReadings> precedence, Func<RoomBlockReadings, TReading?> read, Func<TReading, string> key)
        where TReading : struct
    {
        var written = new HashSet<TReading>();
        text.Append("    /// <summary>The behaviour a write of each ").Append(description).Append(" keeps.</summary>\n");
        text.Append("    internal static readonly IReadOnlyDictionary<").Append(readingType).Append(", RoomBlockReadings> ").Append(name)
            .Append(" = new Dictionary<").Append(readingType).Append(", RoomBlockReadings>\n    {\n");
        foreach (RoomBlockReadings readings in precedence)
        {
            if (read(readings) is not { } reading || !written.Add(reading))
                continue;
            text.Append("        [").Append(key(reading)).Append("] = ").Append(Readings(readings)).Append(",\n");
        }
        text.Append("    };\n\n");
    }

    /// <summary>One behaviour's source, its slope and extension readings on a second line.</summary>
    private static string Readings(RoomBlockReadings readings) => new StringBuilder()
        .Append("new(")
        .Append(Reaction(readings.Shootable)).Append(", ")
        .Append(Reaction(readings.Bombable)).Append(", ")
        .Append(Reaction(readings.Special)).Append(", ")
        .Append(Reaction(readings.SpecialAir)).Append(", ")
        .Append(Reaction(readings.Spike)).Append(", ")
        .Append(Reaction(readings.Grapple)).Append(",\n").Append(ContinuationIndent)
        .Append(Slope(readings.Slope)).Append(", ")
        .Append(readings.ExtensionOffset.ToString(System.Globalization.CultureInfo.InvariantCulture)).Append(readings.ResolvedByArea ? ", ResolvedByArea: true" : "").Append(')')
        .ToString();

    /// <summary>A slope's source.</summary>
    private static string Slope(SlopeGeometry slope) =>
        $"new(SlopeShapeDefinitions.{slope.Shape.Name}, BlockMirroring.{slope.Mirroring})";

    /// <summary>A reading's source: the reaction by its type and name, or null for a kind with no reaction (#1742).</summary>
    private static string Reaction<TReaction>(TReaction? reaction)
        where TReaction : struct, Enum =>
        reaction is { } named ? Named(named) : "null";

    /// <summary>A reaction's source, by its type and name.</summary>
    private static string Named<TReaction>(TReaction reaction)
        where TReaction : struct, Enum => $"{typeof(TReaction).Name}.{reaction}";
}
