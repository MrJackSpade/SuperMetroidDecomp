using SuperMetroid.Core.Fx;
using SuperMetroid.Core.Fx.Artwork;

namespace SuperMetroid.Verification.Fx;

/// <summary>Checks animated room-FX atlas source windows, byte geometry, and standalone-frame roles.</summary>
internal static class LookupFxAtlasSegmentsVerification
{
    /// <summary>
    /// Independent pre-conversion strip order captured from the supported ROM: simple
    /// animation, rightward treadmill, complete statue strip, then spores. This
    /// comparison metadata is not generated by the catalog under test. The atlas is keyed by picture identity (#1415);
    /// these addresses check that the import reads each segment from where it was captured.
    /// </summary>
    private static OriginalRoomFxAtlasSegment[] OriginalRoomFxAtlasSegments() =>
    [
        new(0x8791e4, 0x0040),
        new(0x879224, 0x0040),
        new(0x879264, 0x0040),
        new(0x8792a4, 0x0040),
        new(0x879164, 0x0020),
        new(0x879184, 0x0020),
        new(0x8791a4, 0x0020),
        new(0x8791c4, 0x0020),
        new(0x87a564, 0x0040),
        new(0x87a5a4, 0x0040),
        new(0x87a5e4, 0x0040),
        new(0x87a624, 0x0040),
        new(0x87a664, 0x0040),
        new(0x87a6a4, 0x0040),
        new(0x87a6e4, 0x0040),
        new(0x87a724, 0x0040),
        new(0x87a764, 0x0040),
        new(0x87a7a4, 0x0040),
        new(0x87a874, 0x0050),
        new(0x87a8c4, 0x0050),
        new(0x87a914, 0x0050),
        new(0x87a964, 0x0050),
        new(0x87a9b4, 0x0050),
        new(0x878e64, 0x0020),
        new(0x878e84, 0x0020),
        new(0x878ea4, 0x0020),
        new(0x878ec4, 0x0020),
        new(0x879364, 0x0600),
        new(0x87a7e4, 0x0030),
        new(0x87a814, 0x0030),
        new(0x87a844, 0x0030),
        new(0x879d84, 0x0080),
        new(0x879e04, 0x0080),
        new(0x879e84, 0x0080),
    ];

    /// <summary>The cartridge address of the shared Tourian statue strip, the one segment that is not a standalone picture.</summary>
    private const int StatueStrip = 0x879364;

    /// <summary>Checks native source order, editable windows, statue aliases, and invalid addresses.</summary>
    internal static void VerifyRoomFxAtlasSegmentSources(SuperMetroid.Core.Hardware.ISnesAddressSpace rom)
    {
        var expected = OriginalRoomFxAtlasSegments();
        var actual = RoomFxAnimatedTileAtlasFormat.Segments.ToArray();
        AssertEqual(expected.Length, actual.Length, "Atlas original segment count");
        var bytes = Enumerable.Range(0, 3616).Select(index => (byte)(index * 37 + index / 256)).ToArray();
        var atlas = new RoomFxAnimatedTileAtlas(bytes);
        int offset = 0;
        foreach (var segment in expected)
        {
            if (segment.Source != StatueStrip)
            {
                AssertTrue(atlas.TryResolve(segment.Source, segment.ByteCount, out var data),
                    "Original standalone source resolves without a dictionary");
                AssertTrue(bytes.AsSpan(offset, segment.ByteCount).SequenceEqual(data.Span),
                    "Source selects its original editable pixel window");
                AssertThrows<InvalidDataException>(() => atlas.TryResolve(segment.Source,
                    segment.ByteCount + 1, out _), "Altered standalone geometry rejects");
            }
            offset += segment.ByteCount;
        }
        foreach (ushort header in new ushort[] { 0x854c, 0x8552, 0x8558, 0x855e })
        foreach (var frame in OriginalTourianFrames(rom, header))
        {
            int size = ReadVerificationWord(rom, 0x870002 + header);
            AssertTrue(atlas.TryResolve(frame.Source, size, out var data), "Original shared statue window resolves");
            AssertTrue(bytes.AsSpan(1552 + frame.Source - 0x879364, size).SequenceEqual(data.Span),
                "Statue alias still selects its original strip window");
            AssertThrows<InvalidDataException>(() => atlas.TryResolve(frame.Source, size + 1, out _),
                "Altered statue geometry rejects after streamed lookup");
        }
        foreach (int missing in new[] { int.MinValue, 0, 0x878e63, 0x878e65, 0x87a9b5, int.MaxValue })
            AssertTrue(!atlas.TryResolve(missing, 32, out _), "Non-frame source remains unresolved");
        for (int index = 0; index < expected.Length; index++)
            AssertEqual(expected[index].Source, RoomFxAnimatedTileSources.Of(actual[index]).Value,
                "Atlas source order: the import reads each segment from its original address");
    }

    /// <summary>Checks each strip length and the complete 3,616-byte atlas geometry.</summary>
    internal static void VerifyRoomFxAtlasSegmentSizes()
    {
        var expected = OriginalRoomFxAtlasSegments();
        var actual = RoomFxAnimatedTileAtlasFormat.Segments.ToArray();
        for (int index = 0; index < expected.Length; index++)
            AssertEqual(expected[index].ByteCount, actual[index].ByteCount, "Atlas segment length");
        AssertEqual(3616, actual.Sum(segment => segment.ByteCount), "Complete original PNG byte geometry");
    }

    /// <summary>Distinguishes standalone frames from the shared statue strip without materializing segments.</summary>
    internal static void VerifyRoomFxAtlasSegmentRoles()
    {
        var expected = OriginalRoomFxAtlasSegments();
        var actual = RoomFxAnimatedTileAtlasFormat.Segments.ToArray();
        for (int index = 0; index < expected.Length; index++)
            AssertEqual(expected[index].Source != StatueStrip, actual[index] is RoomFxAtlasSegment.Image,
                "Atlas standalone picture or shared strip");
        AssertTrue(RoomFxAnimatedTileAtlasFormat.Segments is not ICollection<RoomFxAtlasSegment>,
            "Segments are streamed without a materialized collection");
    }
}
