    internal static ushort ReadMechanicsWord(ushort address)
    {
        int low = 0;
        int high = Words.Length - 1;
        while (low <= high)
        {
            int middle = low + ((high - low) >> 1);
            RoomSpriteObjectInstructionMechanicsWord candidate = Words[middle];
            if (candidate.Address == address)
                return candidate.Value;
            if (candidate.Address < address)
                low = middle + 1;
            else
                high = middle - 1;
        }

        throw new InvalidDataException(
            $"Room sprite-object instruction mechanics pointer $B4:{address:X4} is not compiled.");
    }

    internal static bool IsCompiledMechanicsByte(int address)
    {
        if ((address & 0xff0000) != 0xb40000)
            return false;
        ushort bankAddress = unchecked((ushort)address);
        for (int index = 0; index < Words.Length; index++)
        {
            ushort wordAddress = Words[index].Address;
            if (bankAddress == wordAddress ||
                bankAddress == unchecked((ushort)(wordAddress + 1)))
            {
                return true;
            }
        }
        return false;
    }

    internal static bool TryGetPresentationWord(int address, out ushort wordAddress)
    {
        wordAddress = 0;
        if ((address & 0xff0000) != 0xb40000)
            return false;
        ushort bankAddress = unchecked((ushort)address);
        for (int index = 0; index < PresentationWords.Length; index++)
        {
            ushort candidate = PresentationWords[index];
            if (bankAddress == candidate ||
                bankAddress == unchecked((ushort)(candidate + 1)))
            {
                wordAddress = candidate;
                return true;
            }
        }
        return false;
    }
