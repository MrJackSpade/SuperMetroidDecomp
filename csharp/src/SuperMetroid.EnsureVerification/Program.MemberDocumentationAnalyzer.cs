using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using SuperMetroid.EnsureAnalyzer;

namespace SuperMetroid.EnsureVerification;

/// <summary>Focused checks for documentation on members at every visibility level.</summary>
internal static class MemberDocumentationAnalyzerTests
{
    /// <summary>Confirms private and static declarations receive the same diagnostic as public declarations.</summary>
    internal static void VerifyMemberDocumentationAnalyzer()
    {
        Expect("/// <summary>Container.</summary>\nclass C { private void M() { } }", "M");
        Expect("/// <summary>Container.</summary>\nclass C { private static void M() { } }", "M");
        Expect("/// <summary>Container.</summary>\nclass C { internal static int F; }", "FieldDeclaration");
        Expect("/// <summary>Container.</summary>\nclass C { protected int P { get; } }", "P");
        Expect("/// <summary>Container.</summary>\nclass C { public void M() { } }", "M");
        Expect("class C { }", "C");
        Expect("/// <summary>Container.</summary>\nclass C { private C() { } }", "C");
        Expect("/// <summary>Container.</summary>\nclass C { private class N { } }", "N");
        Expect("/// <summary>Values.</summary>\nenum E { A }", "A");
        Expect("delegate void Callback();", "Callback");
        Expect("/// <summary>Extensions.</summary>\nstatic class E { extension(string value) { } }", "ExtensionBlockDeclaration");
        Expect("/// <summary>Container.</summary>\nclass C { public event System.Action? Changed; }", "EventFieldDeclaration");
        Expect("/// <summary>Container.</summary>\nclass C { private int this[int index] => index; }", "IndexerDeclaration");
        Expect("/// <summary>Container.</summary>\nclass C { // Ordinary comments do not satisfy the XML documentation rule.\nprivate void M() { } }", "M");
        Expect("/// <summary>Container.</summary>\nclass C { /// <summary>Method.</summary>\nprivate static void M() { } }");
        Expect("// <auto-generated>\nclass C { private static void M() { } }", generated: true);
        Expect("class C { private static void M() { } }", generated: true, path: "C.Generated.cs");
    }

    /// <summary>Checks the exact analyzer diagnostic for one source declaration.</summary>
    private static void Expect(string source, string? name = null, bool generated = false, string path = "C.cs")
    {
        var tree = CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Preview), path: path);
        var compilation = CSharpCompilation.Create("MemberDocumentationCase", [tree], AnalyzerTests.References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        var diagnostics = compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(
            new MemberDocumentationAnalyzer())).GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();
        int expected = generated || name is null ? 0 : 1;
        if (diagnostics.Length != expected || diagnostics.Any(d => d.Id != MemberDocumentationAnalyzer.Id ||
            d.Severity != DiagnosticSeverity.Error || (name is not null && !d.GetMessage().Contains(name, StringComparison.Ordinal))))
        {
            throw new InvalidOperationException(
                $"Expected {expected} documentation diagnostic(s) for {name}; got [{string.Join("; ", diagnostics.Select(d => d.ToString()))}] in {source}");
        }
    }
}
