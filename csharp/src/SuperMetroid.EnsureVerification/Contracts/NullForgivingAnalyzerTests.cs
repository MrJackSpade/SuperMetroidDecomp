using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using SuperMetroid.EnsureAnalyzer.Contracts;
using SuperMetroid.EnsureVerification.Harness;

namespace SuperMetroid.EnsureVerification.Contracts;

/// <summary>Checks the #623 null-forgiving operator ban.</summary>
internal static class NullForgivingAnalyzerTests
{
    /// <summary>Positive and negative cases for SME6380, then the projects the analyzer cannot analyze itself.</summary>
    internal static void VerifyNullForgivingAnalyzer()
    {
        // Every postfix suppression is reported, wherever it appears.
        Expect("class C { string? s; int M() => s!.Length; }", 1, "'s!'");
        Expect("class C { string? F() => null; int M() => F()!.Length; }", 1, "'F()!'");
        Expect("class C { object? o; int M() => ((string)o!).Length; }", 1);
        Expect("class C { string s = null!; }", 1, "'null!'");
        Expect("class C { string s = default!; }", 1, "'default!'");
        Expect("class C { string? a; string? b; int M() => a!.Length + b!.Length; }", 2);
        Expect("class C { C? Next; int V; int M() => Next!.Next!.V; }", 2);
        Expect("class G<T> { T? value; T M() => value!; }", 1);
        Expect("class C { string? s; int M() =>\n    s\n    !\n    .Length; }", 1);
        Expect("// <auto-generated/>\nclass C { string s = null!; }", 1);

        // Logical negation, inequality, null-conditional, null-coalescing, guards and honest attributes stay legal.
        Expect("class C { bool M(bool b) => !b; }");
        Expect("class C { bool M(int a, int b) => a != b; }");
        Expect("class C { string? s; int? M() => s?.Length; }");
        Expect("class C { string? s; int M() => (s ?? \"\").Length; }");
        Expect("class C { string? s; int M() => s is null ? 0 : s.Length; }");
        Expect("class C { string? s; int M() => (s ?? throw new System.InvalidOperationException()).Length; }");
        Expect("using System.Diagnostics.CodeAnalysis; class C { bool TryGet([NotNullWhen(true)] out string? s) { s = \"\"; return true; } int M() => TryGet(out string? s) ? s.Length : 0; }");
        Expect("class C { bool M(bool? b) => !(b ?? false); }");

        VerifyAnalyzerProjectsHaveNoSuppressions();
    }

    /// <summary>
    /// The analyzer projects and this verifier do not load the analyzer they build, so their sources are checked here
    /// by the same syntax rule.
    /// </summary>
    private static void VerifyAnalyzerProjectsHaveNoSuppressions()
    {
        string source = SourceDirectory();
        string[] projects = ["SuperMetroid.EnsureAnalyzer", "SuperMetroid.EnsureAnalyzer.CodeFixes", "SuperMetroid.EnsureVerification"];
        foreach (string project in projects)
        {
            string directory = Path.Combine(source, project);
            if (!Directory.Exists(directory))
                throw new DirectoryNotFoundException($"Analyzer project sources were not found at {directory}.");
            foreach (string file in Directory.EnumerateFiles(directory, "*.cs", SearchOption.AllDirectories))
            {
                string normalized = file.Replace('\\', '/');
                if (normalized.Contains("/bin/") || normalized.Contains("/obj/"))
                    continue;
                SyntaxNode root = CSharpSyntaxTree.ParseText(File.ReadAllText(file), new CSharpParseOptions(LanguageVersion.Preview), file).GetRoot();
                if (root.DescendantNodes().OfType<PostfixUnaryExpressionSyntax>()
                    .FirstOrDefault(node => node.IsKind(SyntaxKind.SuppressNullableWarningExpression)) is { } found)
                {
                    int line = found.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
                    throw new InvalidOperationException($"{file}({line}): null-forgiving operator '{found}' is banned (SME6380).");
                }
            }
        }
    }

    /// <summary>The repository's <c>csharp/src</c> directory, found from the working directory upward.</summary>
    internal static string SourceDirectory()
    {
        for (DirectoryInfo? directory = new(Directory.GetCurrentDirectory()); directory is not null; directory = directory.Parent)
        {
            string candidate = Path.Combine(directory.FullName, "csharp", "src");
            if (Directory.Exists(Path.Combine(candidate, "SuperMetroid.EnsureAnalyzer")))
                return candidate;
            if (Directory.Exists(Path.Combine(directory.FullName, "SuperMetroid.EnsureAnalyzer")))
                return directory.FullName;
        }
        throw new DirectoryNotFoundException($"No csharp/src with SuperMetroid.EnsureAnalyzer above {Directory.GetCurrentDirectory()}.");
    }

    /// <summary>Compiles one source and compares the SME6380 count and an optional message fragment.</summary>
    private static void Expect(string source, int count = 0, string? message = null)
    {
        var tree = CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Preview), path: "Case.cs");
        var compilation = CSharpCompilation.Create("NullForgivingCase", [tree], AnalyzerTests.References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException($"Invalid analyzer fixture: {string.Join("; ", errors.Select(e => e.ToString()))}");
        var diagnostics = compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new NullForgivingAnalyzer()))
            .GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();
        if (diagnostics.Length != count || diagnostics.Any(d => d.Id != NullForgivingAnalyzer.Id || d.Severity != DiagnosticSeverity.Error) ||
            (message is not null && !diagnostics.All(d => d.GetMessage().Contains(message, StringComparison.Ordinal))))
        {
            throw new InvalidOperationException(
                $"Expected {count} {NullForgivingAnalyzer.Id} diagnostic(s) containing '{message}', got [{string.Join("; ", diagnostics.Select(d => d.ToString()))}] in: {source}");
        }
    }
}
