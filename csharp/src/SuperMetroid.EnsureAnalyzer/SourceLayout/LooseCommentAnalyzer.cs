using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using SuperMetroid.EnsureAnalyzer.CartridgeEncoding;

namespace SuperMetroid.EnsureAnalyzer.SourceLayout;

/// <summary>
/// #1378: outside an executable body the only comments are XML documentation attached to a declaration. A loose
/// <c>//</c> or <c>/* */</c> comment beside a field, between members, in a data table or after a member is attached to
/// nothing, so it drifts away from the code it describes when members move; and <c>#region</c> banners group by
/// position the same way. Comments inside a method, constructor, operator, accessor, local function, lambda or
/// top-level statements explain behaviour and stay. Generated sources are analyzed too. The comments a tool requires
/// are accepted by their exact required text: the <c>// &lt;auto-generated/&gt;</c> marker, and the reviewed same-line
/// <c>cartridge-encoding: allow(Class) - reason</c> allowances the encoding inventory reads from the line they excuse.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class LooseCommentAnalyzer : DiagnosticAnalyzer
{
    /// <summary>A comment outside every executable body, or a region directive.</summary>
    public const string Id = "SME6413";

    /// <summary>The generated-code marker that tools require, accepted by its exact text.</summary>
    private const string GeneratedMarker = "// <auto-generated/>";

    /// <summary>Reports a loose comment.</summary>
    private static readonly DiagnosticDescriptor CommentRule = new(
        Id,
        "Comment outside an executable body",
        "This comment is outside every executable body; move it into the XML documentation of the declaration it describes, give the data it explains a name, or delete it",
        "Architecture",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        description: "Outside executable bodies only XML documentation comments are allowed, so a comment cannot drift from its declaration (#1378).");

    /// <summary>Reports a region directive.</summary>
    private static readonly DiagnosticDescriptor RegionRule = new(
        Id,
        "Region directive",
        "'{0}' groups members by position; delete it and express a real grouping as a type",
        "Architecture",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        description: "Region banners group members by position, which drifts like a loose comment (#1378).");

    /// <inheritdoc />
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => [CommentRule, RegionRule];

    /// <inheritdoc />
    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterSyntaxTreeAction(AnalyzeTree);
    }

    /// <summary>Reports every loose comment and region directive in the tree.</summary>
    private static void AnalyzeTree(SyntaxTreeAnalysisContext context)
    {
        if (OneTypePerFileAnalyzer.IsThirdPartyGenerated(context.Tree.FilePath) || IsSdkBuildOutput(context.Tree, context.CancellationToken))
            return;
        SyntaxNode root = context.Tree.GetRoot(context.CancellationToken);
        foreach (SyntaxTrivia trivia in root.DescendantTrivia(descendIntoTrivia: false))
        {
            if (trivia.IsKind(SyntaxKind.RegionDirectiveTrivia) || trivia.IsKind(SyntaxKind.EndRegionDirectiveTrivia))
            {
                context.ReportDiagnostic(Diagnostic.Create(RegionRule, trivia.GetLocation(),
                    trivia.IsKind(SyntaxKind.RegionDirectiveTrivia) ? "#region" : "#endregion"));
                continue;
            }
            if (!trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) && !trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
                continue;
            string text = trivia.ToString();
            if (text == GeneratedMarker || CartridgeEncodingScanner.IsAllowanceComment(text) || IsInsideExecutableBody(trivia))
                continue;
            context.ReportDiagnostic(Diagnostic.Create(CommentRule, trivia.GetLocation()));
        }
    }

    /// <summary>
    /// Whether <paramref name="tree"/> is a generated file the .NET SDK writes into a project's intermediate output
    /// (assembly attributes, the target-framework attribute, framework source generators' output). The repository
    /// authors no generator for these and cannot change their text, so they are not repository source.
    /// </summary>
    private static bool IsSdkBuildOutput(SyntaxTree tree, CancellationToken cancellation) =>
        tree.FilePath.Replace('\\', '/').Contains("/obj/", StringComparison.Ordinal) && GeneratedSource.IsGenerated(tree, cancellation);

    /// <summary>Whether <paramref name="trivia"/> lies within the span of an executable body.</summary>
    internal static bool IsInsideExecutableBody(SyntaxTrivia trivia)
    {
        int position = trivia.SpanStart;
        for (SyntaxNode? node = trivia.Token.Parent; node is not null; node = node.Parent)
        {
            SyntaxNode? body = node switch
            {
                BlockSyntax block when block.Parent is BaseMethodDeclarationSyntax or AccessorDeclarationSyntax
                    or LocalFunctionStatementSyntax or AnonymousFunctionExpressionSyntax => block,
                ArrowExpressionClauseSyntax arrow => arrow,
                AnonymousFunctionExpressionSyntax { ExpressionBody: { } expression } => expression,
                GlobalStatementSyntax statement => statement,
                _ => null,
            };
            if (body is not null && body.Span.Contains(position))
                return true;
        }
        return false;
    }
}
