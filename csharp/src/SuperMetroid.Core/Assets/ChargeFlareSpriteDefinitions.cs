                ushort first = spark < 12 ? ProjectileFlareSpritemaps_FlareSlowSparks_FacingRight_0 :
                    ProjectileFlareSpritemaps_FlareSlowSparks_FacingLeft_0;
                return (ushort)(first + spark % 12 * 17);
